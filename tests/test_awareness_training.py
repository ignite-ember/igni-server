"""`docs/AWARENESS_TRAINING.md` must teach this system, not security.

C8, OR-3. Awareness training is the control easiest to satisfy
dishonestly — buy a course, play a video, keep the certificates — so the
syllabus is derived rather than written, from two things the repository
already knows:

* **the policy clauses the software does not enforce.** `POLICIES.md`
  already separates those, because a policy claiming an unenforced
  control is the failure that document exists to avoid. A clause the
  system enforces cannot be got wrong by a person; a clause only a
  person upholds is the whole surface this control addresses;
* **risks with a recorded instance** in `RISK_ASSESSMENT.md` — things
  that went wrong here, not industry anecdotes.

The rules, and the second is the one that earns its keep:

* **every unenforced clause appears**, so an awkward topic cannot be
  quietly shed;
* **nothing appears that the software enforces**, because teaching
  somebody to do what the system already refuses to let them get wrong
  is how a syllabus teaches its audience to ignore it;
* **every module's outcome is written, not templated.** The first
  version derived the outcomes too, and produced seven interchangeable
  modules saying "state that the software does not enforce this" — the
  exact padding the document's closing section warns about, generated by
  the tool that warns about it. The shape is derived; the substance has
  to be written, and the generator refuses to render until it is;
* **every cited risk has an instance.** A module claiming to teach from
  experience must point at experience.
"""

from __future__ import annotations

import importlib.util
import pathlib
import subprocess
import sys

import pytest

_ROOT = pathlib.Path(__file__).resolve().parent.parent
_GENERATOR = _ROOT / 'tools/generate_awareness_training.py'
_DOC = _ROOT / 'docs/AWARENESS_TRAINING.md'

_SPEC = importlib.util.spec_from_file_location('awareness_generator', _GENERATOR)
assert _SPEC and _SPEC.loader, f'cannot load {_GENERATOR}'
_GEN = importlib.util.module_from_spec(_SPEC)
sys.modules['awareness_generator'] = _GEN
_SPEC.loader.exec_module(_GEN)

PLACEHOLDER = _GEN.PLACEHOLDER
render = _GEN.render
modules = _GEN.modules


class TestTheDocumentItself:
    def test_it_exists_and_says_it_is_generated(self):
        assert _DOC.exists(), _DOC
        text = _DOC.read_text()
        assert 'GENERATED by tools/generate_awareness_training.py' in text
        assert len(text.splitlines()) > 120

    def test_the_committed_file_matches_the_generator(self):
        assert (
            _DOC.read_text() == render()
        ), 'docs/AWARENESS_TRAINING.md and its generator disagree. Regenerate with `make docs`.'

    def test_the_generator_agrees_from_the_command_line(self):
        result = subprocess.run(  # noqa: S603
            [sys.executable, str(_GENERATOR), '--check'],
            capture_output=True,
            text=True,
            cwd=_ROOT,
        )
        assert result.returncode == 0, result.stderr or result.stdout

    def test_every_module_appears(self):
        text = _DOC.read_text()
        missing = [m.ref for m in modules() if f'### {m.ref} —' not in text]
        assert not missing, missing


class TestTheSyllabusIsDerived:
    def test_the_derivation_found_something(self):
        """A comparison against an empty set would pass everything, and
        an empty syllabus is the shape this control fails in."""
        unenforced = _GEN.unenforced_clauses()
        observed = _GEN.observed_risks()

        assert len(unenforced) >= 5, [c.ref for c in unenforced]
        assert len(observed) >= 10, [r.ref for r in observed]

    def test_every_unenforced_clause_has_a_module(self):
        """The completeness direction. A clause dropped from the syllabus
        is a topic nobody is taught and nobody notices."""
        assert not _GEN.clauses_without_a_module()

    def test_no_module_teaches_something_the_software_enforces(self):
        """Padding. It teaches the audience that the training is not
        worth their attention, which costs more than the module."""
        assert not _GEN.modules_for_enforced_clauses()

    def test_no_outcome_is_written_for_a_clause_that_is_enforced_now(self):
        """The other direction: if the software starts enforcing
        something, the module must go rather than linger as material
        about a risk that no longer exists."""
        assert not _GEN.outcomes_for_unknown_clauses()

    def test_every_cited_risk_exists_and_has_an_instance(self):
        assert not _GEN.unknown_risks()
        assert not _GEN.risks_cited_without_an_instance()

    def test_the_syllabus_follows_the_policies_own_order(self):
        """So a reader can hold the two documents side by side. A
        syllabus in an order of its own invites the question of what the
        order means."""
        derived = [m.clauses[0] for m in _GEN.derived_modules()]
        expected = [c.ref for c in _GEN.unenforced_clauses()]

        assert derived == expected


class TestTheOutcomesAreRealOutcomes:
    """The rule that came out of getting this wrong.

    Deriving the topic list takes no judgement. Deriving the *content*
    took none either, and that was the bug: every module read "state
    that the software does not enforce this, name who does", which is
    seven modules that could be one.
    """

    def test_the_generator_refuses_without_a_written_outcome(self):
        assert not _GEN.clauses_without_an_outcome()

    def test_no_outcome_is_a_restatement_of_the_clause(self):
        """The templated version was a paraphrase of the clause plus its
        owner. A real outcome says what somebody does differently."""
        for module in modules():
            assert module.outcome.strip() != module.title.strip(), module.ref
            assert 'name who does' not in module.outcome, f'{module.ref} has the templated outcome back'

    def test_no_two_modules_share_an_outcome(self):
        """Interchangeable modules are padding by another route."""
        outcomes = [m.outcome for m in modules()]
        duplicates = {o for o in outcomes if outcomes.count(o) > 1}

        assert not duplicates, f'{len(duplicates)} outcome(s) appear on more than one module'

    def test_every_outcome_is_something_a_person_can_be_asked_to_do(self):
        """ "Understands the importance of" cannot be assessed, so it
        cannot be evidence."""
        assert not _GEN.modules_without_a_checkable_outcome()

    def test_the_document_says_assessment_is_not_included(self):
        """Because inventing a pass mark here would be inventing
        evidence, which is the thing this whole document is against."""
        prose = ' '.join(_DOC.read_text().split())
        assert 'inventing a pass mark here would be inventing evidence' in prose


class TestWhatItRefusesToDo:
    @pytest.mark.parametrize(
        'field',
        [
            'Organisation',
            'Owner of this programme',
            'Delivered on joining, within',
            'Repeated every',
            'Record of completion kept at',
            'Approved by',
            'Date of approval',
        ],
    )
    def test_the_binding_fields_are_asked_for_and_left_blank(self, field):
        text = _DOC.read_text()
        row = next((line for line in text.splitlines() if line.startswith(f'| {field} |')), None)

        assert row, f'the programme table no longer asks for: {field}'
        assert PLACEHOLDER in row, f'{field} has been filled in by the generator: {row}'

    def test_it_says_it_is_not_training(self):
        prose = ' '.join(_DOC.read_text().split())
        assert 'It is not training.' in prose
        assert 'no evidence that anybody has read a word' in prose

    def test_it_asks_for_the_revision_in_the_completion_record(self):
        """The part usually left out, and the part that matters: this
        file is regenerated whenever the policies or risks it derives
        from change, so "trained" is a claim about one revision."""
        prose = ' '.join(_DOC.read_text().split())
        assert 'Record the commit.' in prose

    def test_it_does_not_duplicate_generic_material(self):
        prose = ' '.join(_DOC.read_text().split())
        assert 'Phishing, password reuse and device hygiene' in prose
        assert 'this document does not duplicate it' in prose


