"""The models and the migrations must describe the same database.

This is the check that was missing, and its absence was not obvious.
Tests build their schema by running alembic, so a model that
under-declares the schema passes everything: the constraint it forgot to
mention is there anyway, because a migration created it.

What that cost, when it was measured: the models were missing seven
foreign keys, three unique constraints, one partial index and eleven
server defaults. Two consequences, both quiet.

``Base.metadata.create_all`` — used by tooling and by anyone building a
scratch database — produced a schema with no referential integrity on the
org-group tables at all. And the next
``alembic revision --autogenerate`` would have proposed *dropping* the
real constraints, because from its point of view the models are the
intent and the database had drifted. Somebody would have reviewed that
diff, seen a tidy-looking cleanup, and shipped it.

So: one assertion, run against the same migrated database the rest of the
suite uses. If it fails, either a model changed without a migration or a
migration changed without a model, and the failure names which.
"""

from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext
import pytest
from sqlalchemy import create_engine

from app.db.sql.models import Base, load_all_models
from tests.conftest import TEST_DB_URL_SYNC


@pytest.fixture(scope='module')
def differences():
    """Everything alembic would put in the next autogenerated revision."""
    load_all_models()
    engine = create_engine(TEST_DB_URL_SYNC)
    try:
        with engine.connect() as conn:
            context = MigrationContext.configure(
                conn,
                # Both off by default, and both are where the drift was:
                # server defaults on eleven columns, and nothing would
                # have caught a column silently changing type.
                opts={'compare_type': True, 'compare_server_default': True},
            )
            return compare_metadata(context, Base.metadata)
    finally:
        engine.dispose()


def _describe(diffs) -> str:
    return '\n'.join(f'  {d}' for d in diffs)


class TestParity:
    def test_the_models_describe_the_migrated_schema_exactly(self, differences):
        """No tables, columns, constraints, indexes or defaults differ.

        A failure here is not cosmetic. It means one of the two
        descriptions of this database is wrong, and the suite cannot tell
        you which — only that shipping either one alone would produce a
        schema the other does not expect.
        """
        assert differences == [], (
            'The models and the migrations disagree. Alembic would put the '
            f'following in the next autogenerated revision:\n{_describe(differences)}'
        )

    def test_no_constraint_exists_only_in_the_database(self, differences):
        """Called out separately because it is the failure that hides.

        A constraint the migrations create and the models omit is
        invisible in testing — the schema has it either way — right up
        until an autogenerated revision proposes removing it.
        """
        removals = [d for d in differences if isinstance(d, tuple) and str(d[0]).startswith('remove_')]
        assert removals == [], (
            'These exist in the database but not in the models, so the next '
            f'autogenerated revision would drop them:\n{_describe(removals)}'
        )
