"""`docs/POLICIES.md` must not say "shall" about anything unchecked.

C3, OR-2. Policies are the most reliably worthless document in a
compliance pack: downloaded, renamed, and full of sentences nobody
verifies. The auditor reads one, compares it with the system, and finds
the two have never met.

So the document is generated and there is one rule:

> **Every clause names what enforces it, or is marked unenforced with an
> owner.**

The rules here make that stick:

* a clause claiming enforcement must describe a **mechanism** and cite
  something checkable — register rows, all `Verified`, or test files that
  exist. On the first run this caught **six citations to test files that
  do not exist**, all of them names I had guessed rather than looked up,
  which is exactly the "citation to nothing reads as evidence" failure;
* two of those turned out to be real gaps rather than wrong names.
  Nothing asserted the password policy the document states, and nothing
  asserted that CI runs the test suite at all — the second being the
  guard on every other guard in this repository. Both exist now, in
  `test_the_policies_are_enforced.py`;
* an unenforced clause is not deleted and not softened. It is stated,
  marked, and given an owner, because "we intend to" is useful and "we
  do" would be a lie;
* the six fields that make a policy binding — the organisation, the
  owner, the approver, the date, the review interval, the exceptions
  process — stay blank. A generator cannot adopt a policy.
"""

from __future__ import annotations

import importlib.util
import pathlib
import re
import subprocess
import sys

import pytest

_ROOT = pathlib.Path(__file__).resolve().parent.parent
_GENERATOR = _ROOT / 'tools/generate_policies.py'
_POLICIES = _ROOT / 'docs/POLICIES.md'

_SPEC = importlib.util.spec_from_file_location('policy_generator', _GENERATOR)
assert _SPEC and _SPEC.loader, f'cannot load {_GENERATOR}'
_GEN = importlib.util.module_from_spec(_SPEC)
sys.modules['policy_generator'] = _GEN
_SPEC.loader.exec_module(_GEN)

CLAUSES = _GEN.CLAUSES
POLICIES = _GEN.POLICIES
PLACEHOLDER = _GEN.PLACEHOLDER
render = _GEN.render
is_enforced = _GEN.is_enforced
register_rows = _GEN.register_rows


class TestTheDocumentItself:
    def test_it_exists_and_says_it_is_generated(self):
        assert _POLICIES.exists(), _POLICIES
        text = _POLICIES.read_text()
        assert 'GENERATED by tools/generate_policies.py' in text
        assert len(text.splitlines()) > 200

    def test_the_committed_file_matches_the_generator(self):
        assert (
            _POLICIES.read_text() == render()
        ), 'docs/POLICIES.md and its generator disagree. Regenerate:\n    python tools/generate_policies.py'

    def test_the_generator_agrees_from_the_command_line(self):
        result = subprocess.run(  # noqa: S603
            [sys.executable, str(_GENERATOR), '--check'],
            capture_output=True,
            text=True,
            cwd=_ROOT,
        )
        assert result.returncode == 0, result.stderr or result.stdout

    def test_all_four_policies_are_present(self):
        """OR-2 names four: access, cryptography, secure development,
        incident response."""
        text = _POLICIES.read_text()
        assert len(POLICIES) == 4, POLICIES
        for _, title, _ in POLICIES:
            assert f'## {title} policy' in text, title

    def test_every_clause_appears(self):
        text = _POLICIES.read_text()
        missing = [c.ref for c in CLAUSES if f'### {c.ref} —' not in text]
        assert not missing, missing

    def test_every_clause_belongs_to_a_declared_policy(self):
        codes = {code for code, _, _ in POLICIES}
        orphans = sorted(c.ref for c in CLAUSES if c.policy not in codes)
        assert not orphans, f'these clauses belong to no policy: {orphans}'

    def test_no_policy_is_empty(self):
        """A policy heading with no clauses under it is a section title
        pretending to be a policy."""
        for code, title, _ in POLICIES:
            count = sum(1 for c in CLAUSES if c.policy == code)
            assert count >= 3, f'the {title} policy has {count} clause(s)'


class TestEveryShallNamesItsEnforcement:
    """The rule the document exists for."""

    def test_the_register_was_read(self):
        rows = register_rows()
        assert len(rows) > 40, len(rows)
        assert rows.get('AC-11') == 'Verified'

    def test_no_clause_claims_enforcement_without_a_mechanism_or_evidence(self):
        offenders = _GEN.clauses_claiming_without_evidence()
        assert not offenders, offenders

    def test_every_cited_register_row_exists(self):
        unknown = _GEN.unknown_rows()
        assert not unknown, f'these rows are cited and do not exist: {unknown}'

    def test_no_enforced_clause_rests_on_an_unverified_row(self):
        """A clause is a statement that something *is* true. Resting one
        on a `Process` row would be resting it on the register's own
        admission that the thing is not built."""
        offenders = _GEN.unverified_rows()
        assert not offenders, offenders

    def test_every_cited_test_file_exists(self):
        """Six of these were wrong on the first run — names I had guessed
        rather than looked up. A citation to a file that does not exist
        reads exactly like evidence."""
        missing = _GEN.missing_tests()
        assert not missing, missing

    def test_every_cited_test_file_is_a_test(self):
        """A clause citing `app/something.py` would be citing the
        implementation as proof of itself."""
        wrong = sorted(
            f'{c.ref} cites {path}'
            for c in CLAUSES
            for path in c.tests
            if not (path.startswith('tests/') or path.startswith('.github/'))
        )
        assert not wrong, wrong

    def test_an_unenforced_clause_names_an_owner(self):
        assert not _GEN.unenforced_without_an_owner()

    def test_an_unenforced_clause_claims_nothing(self):
        """The other direction: a clause marked unenforced must not also
        cite evidence, or the table reads as though it were handled."""
        contradictory = sorted(c.ref for c in CLAUSES if not is_enforced(c) and (c.rows or c.tests))
        assert not contradictory, contradictory

    def test_no_clause_says_a_document_is_missing(self):
        """F149. ``IR-P7`` said *"This plan does not exist"* long after
        C4 wrote ``docs/INCIDENT_RESPONSE.md``, and the awareness syllabus
        quoted it as the reason its module exists — so a module taught
        that a document was missing from the repository containing it.
        ``IR-P9`` had the same sentence about ``SECURITY.md``.

        A clause's prose may say what is not *enforced*; it may not say a
        file is absent, because that claim goes stale the day somebody
        writes the file, and nothing else would notice."""
        stale = sorted(
            c.ref
            for c in CLAUSES
            if re.search(r'does not exist|is not written|has not been written', c.enforcement + c.unenforced_owner)
        )
        assert not stale, f'these clauses say a document is missing: {stale}'

    def test_every_path_a_clause_names_exists(self):
        """The other half of F149: a clause naming the document that
        answers it must name one that is there."""
        quoted = re.compile(r'`((?:docs|tools|app|charts|tests)/[\w./-]+|[A-Z_]+\.md)`')
        named = {(c.ref, path) for c in CLAUSES for path in quoted.findall(c.enforcement + c.unenforced_owner)}
        assert ('IR-P7', 'docs/INCIDENT_RESPONSE.md') in named, 'the pattern does not see the clause behind it'

        def exists(path: str) -> bool:
            # A bare `NAME.md` is a sibling in docs/ or a file at the root.
            return (_ROOT / path).exists() or (_ROOT / 'docs' / path).exists()

        missing = sorted(f'{ref} names {path}' for ref, path in named if not exists(path))
        assert not missing, missing

    def test_the_document_marks_each_one_either_way(self):
        """Rendered, not just modelled. A render that dropped the
        `Enforced.` / `Not enforced` line would pass everything above."""
        text = _POLICIES.read_text()
        for clause in CLAUSES:
            body = text.split(f'### {clause.ref} —')[1].split('\n###')[0]
            if is_enforced(clause):
                assert '**Enforced.**' in body, f'{clause.ref} is not marked enforced'
                assert 'Evidence:' in body, f'{clause.ref} shows no evidence'
            else:
                assert 'Not enforced by the software' in body, f'{clause.ref} is not marked'
                assert PLACEHOLDER in body, f'{clause.ref} carries no placeholder'


class TestItStatesWhatTheCodeDoes:
    def test_the_password_numbers_match_the_validator(self):
        """The document says eight characters and four classes because
        that is what the code requires. If somebody changes the
        validator, this fails — and the point of a generated policy is
        that the document changes with the product rather than after it.
        """
        source = (_ROOT / 'app/api/base_v1/schema/auth.py').read_text()
        assert 'len(password) < 8' in source, 'the validator changed; AC-P4 needs updating'
        prose = ' '.join(_POLICIES.read_text().split())
        assert 'at least eight characters' in prose

    def test_the_token_lifetime_matches_the_issuer(self):
        source = (_ROOT / 'app/services/auth/jwt_service.py').read_text()
        assert 'timedelta(days=30)' in source, 'the token lifetime changed; AC-P6 needs updating'
        prose = ' '.join(_POLICIES.read_text().split())
        assert 'thirty days' in prose

    def test_the_key_sizes_match_the_code(self):
        checks = (_ROOT / 'app/security/startup_checks.py').read_text()
        assert '_MIN_SHARED_SECRET_LENGTH = 32' in checks, 'the minimum changed; CR-P4 needs updating'
        keys = (_ROOT / 'app/services/identity/jwk.py').read_text()
        assert 'KEY_SIZE = 2048' in keys, 'the signing key size changed; CR-P4 needs updating'
        prose = ' '.join(_POLICIES.read_text().split())
        assert 'thirty-two characters' in prose
        assert '2048-bit RSA key' in prose

    def test_it_does_not_claim_multi_factor_authentication(self):
        """The software does not implement MFA. A policy claiming it
        would be the archetype of the sentence that has never met the
        system — and it is the single most commonly claimed control in a
        security questionnaire.
        """
        prose = ' '.join(_POLICIES.read_text().split())
        assert 'The software does not implement MFA' in prose
        mfa_clause = next(c for c in CLAUSES if 'Multi-factor' in c.shall)
        assert not is_enforced(mfa_clause), 'MFA is marked enforced and is not implemented'


class TestWhatOnlyAnOrganisationCanDo:
    @pytest.mark.parametrize(
        'field',
        [
            'Organisation these policies bind',
            'Policy owner',
            'Approved by',
            'Date of approval',
            'Review interval',
            'Exceptions process',
        ],
    )
    def test_the_binding_fields_are_asked_for_and_left_blank(self, field):
        text = _POLICIES.read_text()
        row = next((line for line in text.splitlines() if line.startswith(f'| {field} |')), None)
        assert row, f'the policies no longer ask for: {field}'
        assert PLACEHOLDER in row, f'{field} has been filled in by the generator: {row}'

    def test_the_outstanding_list_is_complete(self):
        """Everything unenforced appears in one table, because an
        organisation adopting these policies is committing to that list
        and should not have to assemble it by reading thirty-five
        clauses."""
        text = _POLICIES.read_text()
        table = text.split('## Everything not enforced here, in one place')[1].split('\n## ')[0]
        for clause in CLAUSES:
            listed = f'| {clause.ref} |' in table
            assert listed == (
                not is_enforced(clause)
            ), f'{clause.ref} is {"missing from" if not listed else "wrongly in"} the outstanding list'

    def test_it_refuses_the_weasel_words(self):
        """ "Appropriate", "adequate", "as necessary" — a requirement whose
        test is somebody's judgement is not a requirement, and these are
        the words that let a policy sound binding while promising
        nothing."""
        for clause in CLAUSES:
            lowered = clause.shall.lower()
            for weasel in ('as appropriate', 'where appropriate', 'adequate', 'as necessary', 'best effort'):
                assert weasel not in lowered, f'{clause.ref} says {weasel!r}'

    def test_it_quotes_no_count_that_will_drift(self):
        """A number in a generated document is either already wrong or a
        coupling that makes the document stale.

        This one was both. IR-P8 said "ninety-five sections" and was
        wrong by the time it was committed; IR-P4 said "ten metrics",
        which would be wrong the next time one is added. The Statement of
        Applicability made the mirror-image mistake — it *derived* a
        section count, so writing §96 made the committed file stale.
        Neither claim needed a number.
        """
        text = _POLICIES.read_text()
        quoted = re.findall(
            r'\b(\d{2,}|ninety-\w+|eighty-\w+|seventy-\w+|ten|eight|nine)\b'
            r'(?= (?:sections|metrics|alert rules|tests|findings))',
            text,
        )
        # The clause count is rendered from `len(CLAUSES)`, so it cannot
        # be wrong; anything else is prose somebody has to remember.
        #
        # This rule also caught the note explaining the removed count —
        # which quoted it — so the note now describes the mistake without
        # restating the number. F126's shape: a rule reading its own
        # explanation as the thing it forbids.
        assert not quoted, f'these counts will drift: {quoted}'

    def test_it_does_not_claim_certification(self):
        prose = ' '.join(_POLICIES.read_text().split()).lower()
        for phrase in ('we are iso 27001 certified', 'iso 27001 certified', 'soc 2 certified'):
            assert phrase not in prose, f'the policies imply certification: {phrase!r}'

    def test_it_does_not_write_policy_about_people(self):
        """Screening, training and disciplinary process are real controls
        and belong to the organisation. A vendor writing its customers'
        employment policy would be writing fiction, and the SoA marks
        those `organisation` for the same reason."""
        refs = {c.ref for c in CLAUSES}
        assert not any(re.match(r'(HR|PE)-', ref) for ref in refs), refs
        prose = ' '.join(_POLICIES.read_text().split())
        assert 'No commitments about people' in prose
