"""`docs/RECORDS_OF_PROCESSING.md` must not drift from the code.

B4. GDPR Article 30(1) asks the controller for a record of processing
activities. The customer is the controller, but they cannot write the
inventory half without knowing what the software stores and for how
long — so the vendor supplies it, and a vendor-supplied inventory that
goes stale is worse than none, because it reads as assurance.

F139 is why this file exists rather than a careful habit. `COMPLIANCE.md`
was maintained by hand and spent five passes telling customers that
retention, subject access, erasure, an SBOM and the air-gap test did
not exist — all five had been built. The register beside it stayed
correct for the same five passes, and the only difference between them
was a test.

So four rules:

* the committed document is exactly what the generator produces, so a
  migration that changes the classification shows up as a failing test
  rather than as a document nobody re-read;
* every classified table belongs to exactly one activity, so a new
  table has to be given a purpose before the record can be
  regenerated — the same shape as F115's rule that a new column must be
  classified;
* no activity names a table that no longer exists;
* the two fields only a controller can fill in are still marked, and
  the document still refuses to invent a legal basis.
"""

from __future__ import annotations

import pathlib
import subprocess
import sys

import pytest

from app.services.subject_access.classification import ColumnRegistry
from app.services.subject_access.schemas import ColumnClassification, DEAD, INCLUDED

_ROOT = pathlib.Path(__file__).resolve().parent.parent
_GENERATOR = _ROOT / 'tools/generate_records_of_processing.py'
_RECORD = _ROOT / 'docs/RECORDS_OF_PROCESSING.md'

# `tools/` is not a package — the shipped scripts there are entry
# points, not importable modules — so this loads the file by path. The
# generator lives in `tools/` and not `scripts/`, because `/scripts/*`
# is gitignored as "local throwaway debug, secrets, key pools": the
# first version of this went there and was committed as a document and
# a test importing a file the repository did not contain.
import importlib.util  # noqa: E402

_SPEC = importlib.util.spec_from_file_location('rop_generator', _GENERATOR)
assert _SPEC and _SPEC.loader, f'cannot load {_GENERATOR}'
_GEN = importlib.util.module_from_spec(_SPEC)
sys.modules['rop_generator'] = _GEN
_SPEC.loader.exec_module(_GEN)

ACTIVITIES = _GEN.ACTIVITIES
PLACEHOLDER = _GEN.PLACEHOLDER
render = _GEN.render
unassigned_tables = _GEN.unassigned_tables
unknown_tables = _GEN.unknown_tables


def test_the_document_exists_and_was_generated():
    """A hand-edited record is the failure mode this file prevents, so
    the header has to say so."""
    assert _RECORD.exists(), 'the record of processing is missing'
    text = _RECORD.read_text()
    assert 'GENERATED by tools/generate_records_of_processing.py' in text
    assert len(text.splitlines()) > 100, 'the record is suspiciously short'


def test_the_committed_document_matches_the_generator():
    """The rule. Regenerate rather than edit."""
    assert _RECORD.read_text() == render(), (
        'docs/RECORDS_OF_PROCESSING.md and its generator disagree. If the '
        'classification or an activity changed, regenerate:\n'
        '    python tools/generate_records_of_processing.py'
    )


def test_the_generator_agrees_from_the_command_line_too():
    """`--check` is what CI would call, so it has to reach the same
    verdict as importing the module. A check nobody can run in one
    command is a check that gets skipped."""
    result = subprocess.run(  # noqa: S603
        [sys.executable, str(_GENERATOR), '--check'],
        capture_output=True,
        text=True,
        cwd=_ROOT,
    )
    assert result.returncode == 0, result.stderr or result.stdout


def test_every_classified_table_has_a_purpose():
    """Article 30(1)(b) is the purpose of each activity, and a table
    nobody has assigned has no stated purpose — so it would be missing
    from the record entirely, which is the one thing a controller is
    relying on it for."""
    missing = unassigned_tables()
    assert not missing, (
        'these tables hold classified personal data and belong to no '
        f'processing activity: {missing}. Add them to ACTIVITIES in '
        'tools/generate_records_of_processing.py with a purpose.'
    )


def test_no_activity_names_a_table_that_is_gone():
    """The quiet direction: a renamed or dropped table leaves an activity
    describing something that is not there."""
    stale = unknown_tables()
    assert not stale, f'these activities name tables the classification does not have: {stale}'


def test_no_table_is_claimed_by_two_activities():
    """Article 30 wants one purpose per activity. A table in two
    activities means one of the purposes is wrong, and the reader cannot
    tell which."""
    seen: dict[str, str] = {}
    duplicated = []
    for activity in ACTIVITIES:
        for table in activity.tables:
            if table in seen:
                duplicated.append(f'{table}: {seen[table]} and {activity.key}')
            seen[table] = activity.key
    assert not duplicated, '\n'.join(duplicated)


@pytest.mark.parametrize(
    'field',
    [
        'Controller name and contact details',
        'Data protection officer',
        'Legal basis for each activity',
    ],
)
def test_the_controller_fields_are_still_blank(field):
    """The record must not invent these.

    A vendor-supplied Article 30 record that fills in a legal basis is
    worse than one that leaves it marked: it reads as legal advice, and
    the one thing a vendor cannot know is why *this* customer processes
    *this* data. If somebody later fills one in as a convenience, this
    fails.
    """
    text = _RECORD.read_text()
    assert field in text, f'the record no longer asks the controller for: {field}'


def test_every_activity_carries_the_placeholder_for_its_legal_basis():
    """Per activity, not once at the top: legal basis is per processing
    activity in Article 30(1)(b), and a single placeholder at the top
    would let somebody answer it once and think they were done."""
    text = _RECORD.read_text()
    assert text.count(f'**Legal basis (30(1)(b)).** {PLACEHOLDER}') == len(ACTIVITIES), (
        'each activity needs its own legal-basis placeholder; found '
        f'{text.count(f"**Legal basis (30(1)(b)).** {PLACEHOLDER}")} for '
        f'{len(ACTIVITIES)} activities'
    )


def test_the_record_does_not_claim_the_vendor_is_a_processor():
    """It is not one. The software runs in the customer's infrastructure
    and no data reaches the vendor (DP-5), so there is no processor
    relationship and no Article 28 contract to describe. Claiming
    otherwise would invent an obligation and a reassurance at once.
    """
    text = _RECORD.read_text().lower()
    for phrase in ('as your processor', 'we process your data', 'data processing agreement'):
        assert phrase not in text, f'the record implies a processor relationship: {phrase!r}'


def _registry(personal, not_personal=frozenset()):
    """A classification of only the columns given, read the way the generator reads the real one."""
    return ColumnRegistry(personal=personal, not_personal=frozenset(not_personal))


def _row(text, table):
    rows = [line for line in text.splitlines() if line.startswith(f'| `{table}` |')]
    assert len(rows) == 1, f'expected one row for {table}, found {rows}'
    return rows[0]


def test_the_record_names_where_the_classification_lives():
    """A reader is sent to the code to check a column, so both paths have to exist."""
    text = render()
    assert '  app/services/subject_access/, which is itself asserted against' in text
    assert '`app/services/subject_access/personal_columns.py`, with the reason' in text
    assert (_ROOT / 'app/services/subject_access').is_dir()
    assert (_ROOT / 'app/services/subject_access/personal_columns.py').is_file()
    assert 'subject_access.py' not in text


def test_each_column_lands_under_its_verdict(monkeypatch):
    """Returned, withheld, held-but-dead and not personal each go where the
    verdict says; a dead column counts as held but is listed nowhere."""
    monkeypatch.setattr(
        _GEN,
        '_REGISTRY',
        _registry(
            {
                'users.full_name': INCLUDED,
                'users.email': INCLUDED,
                'users.hashed_password': ColumnClassification.withheld('a hash, not the password'),
                'users.legacy_handle': DEAD,
            },
            {'users.theme', 'users.locale'},
        ),
    )
    text = render()
    assert _row(text, 'users') == '| `users` | 4 | `email`, `full_name` | `hashed_password` | 2 |'
    assert _row(text, 'org_invitations') == '| `org_invitations` | 0 | — | — | 0 |'
    assert 'It covers **4 classified personal-data columns across 1 tables**' in text


def test_the_real_classification_withholds_the_password_hash():
    """One known answer from the real policy, so a verdict that flips shows
    up as more than a drifted document."""
    row = _row(render(), 'users').split(' | ')
    returned, withheld = row[2], row[3]
    assert '`email`' in returned
    assert '`hashed_password`' not in returned
    assert withheld == '`hashed_password`'


def _run_main(monkeypatch, tmp_path, *args):
    out = tmp_path / 'docs/RECORDS_OF_PROCESSING.md'
    out.parent.mkdir(exist_ok=True)
    monkeypatch.setattr(_GEN, '_ROOT', tmp_path)
    monkeypatch.setattr(_GEN, 'OUT', out)
    monkeypatch.setattr(sys, 'argv', ['generate_records_of_processing.py', *args])
    return _GEN.main(), out


def test_without_check_the_generator_writes_the_record(monkeypatch, tmp_path, capsys):
    code, out = _run_main(monkeypatch, tmp_path)
    assert code == 0
    assert out.read_text() == render()
    assert 'wrote docs/RECORDS_OF_PROCESSING.md' in capsys.readouterr().out


@pytest.mark.parametrize('committed', [None, 'a record somebody edited by hand\n'])
def test_check_fails_on_a_record_that_is_stale_or_missing(monkeypatch, tmp_path, capsys, committed):
    out = tmp_path / 'docs/RECORDS_OF_PROCESSING.md'
    if committed is not None:
        out.parent.mkdir()
        out.write_text(committed)
    code, out = _run_main(monkeypatch, tmp_path, '--check')
    assert code == 1
    assert 'docs/RECORDS_OF_PROCESSING.md is out of date' in capsys.readouterr().err
    assert (out.read_text() if out.exists() else None) == committed, '--check must not write'


def test_a_table_with_no_activity_stops_the_generator_before_it_writes(monkeypatch, tmp_path, capsys):
    monkeypatch.setattr(
        _GEN,
        '_REGISTRY',
        _registry({**_GEN._REGISTRY.personal(), 'brand_new.email': INCLUDED}, _GEN._REGISTRY.not_personal()),
    )
    assert unassigned_tables() == ['brand_new']
    code, out = _run_main(monkeypatch, tmp_path)
    assert code == 1
    assert "belong to no activity, so the record would omit them: ['brand_new']" in capsys.readouterr().err
    assert not out.exists()


def test_every_migrated_table_is_accounted_for():
    assert _GEN.unaccounted_tables() == []
    assert _GEN.misdescribed_tables() == []


def test_a_table_without_personal_data_has_to_be_listed(monkeypatch):
    """Dropping a table from NO_PERSONAL_DATA leaves it unaccounted for."""
    dropped, *rest = _GEN.NO_PERSONAL_DATA
    monkeypatch.setattr(_GEN, 'NO_PERSONAL_DATA', tuple(rest))
    assert _GEN.unaccounted_tables() == [dropped[0]]


@pytest.mark.parametrize('table', ['users', 'a_table_no_migration_creates'])
def test_no_personal_data_cannot_list_a_classified_or_missing_table(monkeypatch, table):
    monkeypatch.setattr(_GEN, 'NO_PERSONAL_DATA', (*_GEN.NO_PERSONAL_DATA, (table, 'nothing')))
    assert _GEN.misdescribed_tables() == [table]
