"""`docs/RISK_ASSESSMENT.md` must not overstate what it knows.

C2, the other half of OR-1. A risk register is the easiest compliance
document to fake and the hardest to check: rows of estimated likelihood
and invented impact, arithmetic on numbers nobody can source.

This one is generated, and the rules are what make it worth reading:

* **treatment state is derived, never declared.** It is a function of
  the statuses of the register rows a risk cites, and those statuses are
  asserted by `test_compliance_tracker_is_current.py`. A risk cannot
  show `treated` while its own evidence is `Process`;
* **every citation resolves** — findings and review sections in
  `REVIEW_FINDINGS.md`, rows in the register, controls in the Statement
  of Applicability;
* **a control the SoA excludes cannot be a treatment.** Declaring a
  control inapplicable and then relying on it is the contradiction an
  auditor looks for, and the first draft did it: R-3 treated egress with
  A 8.23 while the SoA excluded 8.23 on the grounds that there is no
  egress to filter;
* **the prose cannot count higher than its citations.** "Four times"
  beside one finding id is the overclaim this document exists to
  prevent, and it shipped in the first draft twice — R-1 and R-8;
* **every `Process` row must appear as an untreated risk.** A risk
  assessment that omits a known gap is worse than none, and this is what
  stops the document being an inventory of solved problems;
* **appetite, acceptance criteria and approval stay blank.** Whether a
  residual risk is tolerable is a judgement about a business.
"""

from __future__ import annotations

import importlib.util
import pathlib
import re
import subprocess
import sys

import pytest

_ROOT = pathlib.Path(__file__).resolve().parent.parent
_GENERATOR = _ROOT / 'tools/generate_risk_assessment.py'
_ASSESSMENT = _ROOT / 'docs/RISK_ASSESSMENT.md'

_SPEC = importlib.util.spec_from_file_location('risk_generator', _GENERATOR)
assert _SPEC and _SPEC.loader, f'cannot load {_GENERATOR}'
_GEN = importlib.util.module_from_spec(_SPEC)
sys.modules['risk_generator'] = _GEN
_SPEC.loader.exec_module(_GEN)

RISKS = _GEN.RISKS
STATES = _GEN.STATES
PLACEHOLDER = _GEN.PLACEHOLDER
render = _GEN.render
state_of = _GEN.state_of
register_rows = _GEN.register_rows


class TestTheDocumentItself:
    def test_it_exists_and_says_it_is_generated(self):
        assert _ASSESSMENT.exists(), _ASSESSMENT
        text = _ASSESSMENT.read_text()
        assert 'GENERATED by tools/generate_risk_assessment.py' in text
        assert len(text.splitlines()) > 200, 'the assessment is suspiciously short'

    def test_the_committed_file_matches_the_generator(self):
        assert _ASSESSMENT.read_text() == render(), (
            'docs/RISK_ASSESSMENT.md and its generator disagree. Regenerate:\n'
            '    python tools/generate_risk_assessment.py'
        )

    def test_the_generator_agrees_from_the_command_line(self):
        result = subprocess.run(  # noqa: S603
            [sys.executable, str(_GENERATOR), '--check'],
            capture_output=True,
            text=True,
            cwd=_ROOT,
        )
        assert result.returncode == 0, result.stderr or result.stdout

    def test_every_risk_appears_in_it(self):
        text = _ASSESSMENT.read_text()
        missing = [r.ref for r in RISKS if f'| {r.ref} |' not in text]
        assert not missing, missing

    def test_the_risks_are_numbered_without_gaps(self):
        refs = [int(r.ref.removeprefix('R-')) for r in RISKS]
        assert refs == list(range(1, len(RISKS) + 1)), refs


