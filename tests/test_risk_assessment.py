class TestTheStateIsDerived:
    def test_a_risk_citing_only_verified_rows_is_treated(self):
        statuses = {'AA-1': 'Verified', 'AA-2': 'Verified'}
        risk = _GEN._r('R-x', 'x', 'x', rows=('AA-1', 'AA-2'))  # noqa: SLF001
        assert state_of(risk, statuses) == 'treated'

    def test_a_risk_citing_a_process_row_is_not_treated(self):
        """The load-bearing property: the document cannot claim a risk is
        handled while the register says its evidence is unbuilt."""
        statuses = {'AA-1': 'Verified', 'AA-2': 'Process'}
        risk = _GEN._r('R-x', 'x', 'x', rows=('AA-1', 'AA-2'))  # noqa: SLF001
        assert state_of(risk, statuses) == 'partial'

    def test_a_risk_citing_only_process_rows_is_organisational(self):
        risk = _GEN._r('R-x', 'x', 'x', rows=('AA-1',))  # noqa: SLF001
        assert state_of(risk, {'AA-1': 'Process'}) == 'organisation'

    def test_a_risk_citing_only_operator_rows_is_the_operators(self):
        risk = _GEN._r('R-x', 'x', 'x', rows=('AA-1',))  # noqa: SLF001
        assert state_of(risk, {'AA-1': 'Operator'}) == 'operator'

    def test_a_missing_row_does_not_read_as_treated(self):
        """A typo in a row id must not be the thing that marks a risk
        handled. The citation checks catch it first; this is the second
        line, because a check that only fails in one place fails once."""
        risk = _GEN._r('R-x', 'x', 'x', rows=('NOPE-9',))  # noqa: SLF001
        assert state_of(risk, {}) != 'treated'

    def test_every_rendered_state_is_from_the_vocabulary(self):
        statuses = register_rows()
        wrong = sorted(f'{r.ref}={state_of(r, statuses)}' for r in RISKS if state_of(r, statuses) not in STATES)
        assert not wrong, wrong

    def test_the_document_and_the_derivation_agree(self):
        """A render that printed a hardcoded state would pass every check
        above."""
        text = _ASSESSMENT.read_text()
        statuses = register_rows()
        for risk in RISKS:
            row = next(line for line in text.splitlines() if line.startswith(f'| {risk.ref} |'))
            assert f'`{state_of(risk, statuses)}`' in row, f'{risk.ref}: {row[:160]}'


class TestTheProseDoesNotOutrunTheEvidence:
    def test_no_risk_counts_more_occurrences_than_it_cites(self):
        """ "Four times" beside one citation. R-1 and R-8 both did it in
        the first draft — R-1's other three occurrences were found during
        the goal passes and were §86, §90 and §91 rather than numbered
        findings, so the evidence field could not hold them until it
        could hold sections too."""
        offenders = _GEN.understated_evidence()
        assert not offenders, offenders

    def test_no_risk_describes_an_event_it_cannot_point_at(self):
        """R-18 read `not realised` in the table while its own prose said
        the failure had been demonstrated — because it was demonstrated
        in §91, and sections were not citable yet."""
        offenders = _GEN.unclaimed_observations()
        assert not offenders, offenders

    def test_every_risk_says_something_about_what_it_is(self):
        thin = sorted(r.ref for r in RISKS if len(r.threat) < 60 or len(r.observed) < 40)
        assert not thin, f'these have no real threat statement or no real observation: {thin}'

    def test_the_observed_count_in_the_summary_is_derived(self):
        """The document states how many risks were observed rather than
        estimated. A hardcoded number there would be the drift this whole
        approach is against."""
        text = _ASSESSMENT.read_text()
        observed = sum(1 for r in RISKS if r.findings or r.sections)
        assert (
            f'{observed} of the {len(RISKS)} risks' in text
        ), f'the summary does not report {observed} observed of {len(RISKS)}'


class TestNoKnownGapIsOmitted:
    def test_every_process_row_is_somebody_risk(self):
        """The rule that stops this being an inventory of solved
        problems. A `Process` row is a control the register admits is not
        built; if no risk mentions it, the assessment is claiming a
        completeness it does not have."""
        omitted = _GEN.untreated_process_rows()
        assert not omitted, (
            f'these `Process` rows are known gaps that no risk mentions: {omitted}. '
            'A risk assessment that omits a known gap is worse than none.'
        )

    def test_the_treatment_plan_lists_only_what_is_left(self):
        """A plan containing solved problems is a progress report."""
        text = _ASSESSMENT.read_text()
        plan = text.split('## Treatment plan — what is left')[1].split('\n## ')[0]
        statuses = register_rows()
        for risk in RISKS:
            listed = f'| {risk.ref} |' in plan
            treated = state_of(risk, statuses) == 'treated'
            assert (
                listed != treated
            ), f'{risk.ref} is {"treated and in" if treated else "untreated and absent from"} the plan'

    def test_the_plan_says_where_each_open_row_is_tracked(self):
        text = _ASSESSMENT.read_text()
        for row in ('LG-8', 'CM-9', 'OR-1', 'OR-2', 'OR-4', 'OR-6', 'DP-3', 'DP-12'):
            assert f'`{row}`' in text, f'the plan does not say where {row} is tracked'


class TestWhatOnlyAPersonCanDecide:
    @pytest.mark.parametrize(
        'field',
        [
            'Risk appetite',
            'Acceptance criteria (when is a residual risk tolerable)',
            'Review interval',
            'Risk owner (accountable)',
            'Approved by',
            'Date of approval',
        ],
    )
    def test_the_judgement_fields_are_asked_for_and_left_blank(self, field):
        text = _ASSESSMENT.read_text()
        row = next((line for line in text.splitlines() if line.startswith(f'| {field} |')), None)
        assert row, f'the assessment no longer asks for: {field}'
        assert PLACEHOLDER in row, f'{field} has been filled in by the generator: {row}'

    def test_it_does_not_score_what_it_cannot_measure(self):
        """No likelihood or impact numbers. A likelihood for an observed
        event is 1, and an impact figure for "another organisation's
        source was reachable" is a decision about a business rather than
        a measurement. Adding them would make the document worse, so the
        absence is deliberate and stated."""
        text = _ASSESSMENT.read_text()
        assert 'Quantification' in text, 'the assessment no longer explains why it does not score'
        assert not re.search(r'\blikelihood\s*[:=]\s*\d', text, re.I), 'a likelihood score appeared'
        assert not re.search(r'\bimpact\s*[:=]\s*\d', text, re.I), 'an impact score appeared'

    def test_it_admits_what_it_cannot_see(self):
        """140 findings is evidence this codebase was looked at hard, and
        no evidence about what a different angle would find.

        Asserted against whitespace-collapsed prose, because the document
        is hard-wrapped at 80 columns and a phrase check against the raw
        text fails on where the line happened to break — which is a test
        failing for a reason that is not about the document.
        """
        prose = ' '.join(_ASSESSMENT.read_text().split())
        assert 'Risks nobody has thought of' in prose
        assert 'A repository cannot assess its own company' in prose
