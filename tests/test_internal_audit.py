"""`docs/INTERNAL_AUDIT.md` must scope the register that exists.

C9, OR-5. ISO/IEC 27001 clauses 9.2, 9.3 and 10.2.

The document says two things at once, and both have to stay true. The
**practice** exists — the pre-production review (indexed in
`REVIEW_FINDINGS.md`) is clause 10.2 in the shape
the clause asks for, written before anybody called it that. The
**cycle** does not: no schedule, no owner, no minutes.

The rules:

* **every status the register uses has an audit method.** A status is
  added by writing a word in a table, and a programme that silently
  omits one audits everything except the new thing;
* **no method exists for a status nothing uses**, which would be
  instruction for work that never happens;
* **every management review input either cites a file that exists or
  says why nothing answers it.** An agenda pointing at a document nobody
  wrote is the failure this repository keeps finding; an input left
  silent reads as covered;
* **the counts are derived.** The scope table is computed from the
  register at generation, so it cannot drift from the thing it scopes —
  which the road's own Progress table did, in the same repository, while
  summarising a list in the same file.
"""

from __future__ import annotations

import importlib.util
import pathlib
import subprocess
import sys

import pytest

_ROOT = pathlib.Path(__file__).resolve().parent.parent
_GENERATOR = _ROOT / 'tools/generate_internal_audit.py'
_DOC = _ROOT / 'docs/INTERNAL_AUDIT.md'

_SPEC = importlib.util.spec_from_file_location('internal_audit_generator', _GENERATOR)
assert _SPEC and _SPEC.loader, f'cannot load {_GENERATOR}'
_GEN = importlib.util.module_from_spec(_SPEC)
sys.modules['internal_audit_generator'] = _GEN
_SPEC.loader.exec_module(_GEN)

PLACEHOLDER = _GEN.PLACEHOLDER
render = _GEN.render


class TestTheDocumentItself:
    def test_it_exists_and_says_it_is_generated(self):
        assert _DOC.exists(), _DOC
        text = _DOC.read_text()
        assert 'GENERATED by tools/generate_internal_audit.py' in text
        assert len(text.splitlines()) > 100

    def test_the_committed_file_matches_the_generator(self):
        assert (
            _DOC.read_text() == render()
        ), 'docs/INTERNAL_AUDIT.md and its generator disagree. Regenerate with `make docs`.'

    def test_the_generator_agrees_from_the_command_line(self):
        result = subprocess.run(  # noqa: S603
            [sys.executable, str(_GENERATOR), '--check'],
            capture_output=True,
            text=True,
            cwd=_ROOT,
        )
        assert result.returncode == 0, result.stderr or result.stdout


class TestItScopesTheRealRegister:
    def test_the_scan_found_rows(self):
        """A programme scoped over an empty register would pass every
        check below while auditing nothing."""
        rows = _GEN.register_rows()

        assert len(rows) > 40, len(rows)
        assert {ref.split('-')[0] for ref, _ in rows} >= {'AC', 'DP', 'LG', 'OR'}

    def test_every_status_the_register_uses_has_a_method(self):
        assert not _GEN.statuses_without_a_method()

    def test_no_method_describes_work_that_never_happens(self):
        assert not _GEN.methods_for_absent_statuses()

    def test_every_area_prefix_is_named(self):
        assert not _GEN.unknown_areas()

    def test_the_scope_table_matches_the_register(self):
        """Derived, not quoted. The road's Progress table drifted from a
        list in its own file; this is the same failure waiting to happen
        one document over."""
        counts = _GEN.statuses()
        text = _DOC.read_text()
        total = sum(counts.values())

        assert (
            f'| **All** | **{total}** | **{counts["Verified"]}** |' in text
        ), 'the scope table does not agree with the register it counts'

    def test_the_methods_differ_from_each_other(self):
        """A programme saying "review the control" for every status has
        not been thought about. Each status implies different evidence
        and therefore different work."""
        activities = [m.activity for m in _GEN.METHODS]

        assert len(set(activities)) == len(activities)
        for method in _GEN.METHODS:
            assert len(method.activity) > 120, method.status
            assert len(method.nonconformity) > 60, method.status

    def test_unproven_rows_are_audited_before_proven_ones(self):
        """Clause 9.2.1 asks the programme to weigh importance and prior
        results. A row with a test running on every commit is the
        cheapest thing to re-check and the least likely to have moved."""
        order = [m.status for m in sorted(_GEN.METHODS, key=lambda m: m.priority)]

        assert order.index('Process') < order.index('Verified')
        assert order.index('Partial') < order.index('Verified')


class TestTheReviewAgendaIsAnswerable:
    def test_every_cited_file_exists(self):
        assert not _GEN.review_inputs_citing_a_missing_file()

    def test_no_input_is_left_silent(self):
        assert not _GEN.review_inputs_neither_sourced_nor_explained()

    def test_the_mandatory_inputs_are_all_present(self):
        """Clause 9.3.2 lists a) to f), and c) has four sub-items. A
        review that skips one has skipped it whether or not anybody
        noticed."""
        clauses = {i.clause for i in _GEN.REVIEW_INPUTS}
        expected = {
            '9.3.2 a)',
            '9.3.2 b)',
            '9.3.2 c) 1)',
            '9.3.2 c) 2)',
            '9.3.2 c) 3)',
            '9.3.2 c) 4)',
            '9.3.2 d)',
            '9.3.2 e)',
            '9.3.2 f)',
        }

        assert clauses == expected, sorted(expected ^ clauses)

    def test_the_absent_inputs_say_why(self):
        """An empty input a reader can see is different from one nobody
        considered — and both look identical if the document is silent."""
        for item in _GEN.REVIEW_INPUTS:
            if not item.source:
                assert len(item.absent) > 100, item.clause

    def test_audit_results_are_not_claimed_from_the_review_log(self):
        """The tempting shortcut: the pre-production review is audit work in
        substance, so cite it as audit results and the input is answered.
        It was not conducted against a programme, by an independent
        auditor, or to a schedule — so citing it would claim a form that
        was not followed."""
        item = next(i for i in _GEN.REVIEW_INPUTS if i.clause == '9.3.2 c) 3)')

        assert not item.source
        assert 'not conducted against a programme' in item.absent


class TestWhatItRefusesToClaim:
    def test_it_states_the_impartiality_problem(self):
        """Clause 9.2.2 wants auditors who do not audit their own work.
        One person cannot. A programme implying otherwise fails in the
        first interview."""
        prose = ' '.join(_DOC.read_text().split())

        assert '**One person cannot do that.**' in prose
        assert 'reproducibility rather than independence' in prose

    def test_it_does_not_claim_an_audit_happened(self):
        prose = ' '.join(_DOC.read_text().split())

        assert 'Nothing here asserts that anybody did' in prose

    @pytest.mark.parametrize(
        'field',
        [
            'Organisation',
            'Audit programme owner',
            'Internal audit frequency',
            'Management review frequency',
            'Next internal audit due',
            'Next management review due',
            'Where minutes are kept',
            'Approved by',
            'Date of approval',
        ],
    )
    def test_the_cycle_is_asked_for_and_left_blank(self, field):
        text = _DOC.read_text()
        row = next((line for line in text.splitlines() if line.startswith(f'| {field} |')), None)

        assert row, f'the cycle table no longer asks for: {field}'
        assert PLACEHOLDER in row, f'{field} has been filled in by the generator: {row}'

    def test_it_points_findings_at_one_place(self):
        """Two records of the same findings is how two records start
        disagreeing."""
        prose = ' '.join(_DOC.read_text().split())

        assert 'a second place to record them' in prose

    def test_it_separates_itself_from_the_certification_audit(self):
        prose = ' '.join(_DOC.read_text().split())

        assert 'OR-7 and C10' in prose


