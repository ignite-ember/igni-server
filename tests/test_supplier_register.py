"""`docs/SUPPLIERS.md` must describe the supply chain that ships.

C7, OR-4. The answer to "who else touches the data" is nobody, and
saying that with evidence is the deliverable.

The rules, and the second is the one that matters:

* **every image the register names is really pinned** somewhere in the
  build;
* **every image the build pins is in the register.** That is the
  completeness direction: a base image added to a Dockerfile without an
  entry here is exactly how a supply chain drifts away from its
  description, and a supplier register that lies about the supply chain
  has failed at the only thing it does;
* **the three categories stay separate.** Suppliers see no customer
  data; recipients see some only if the customer configures them; the
  vendor sees nothing. A register that treated a base image as a data
  processor would be noise, and one that omitted the model endpoint would
  have missed the only entry that changes a customer's obligations;
* **nothing receives anything by default**, asserted per recipient,
  because "we send telemetry unless you turn it off" is the claim this
  product exists not to make;
* **the fact a customer should check** — the unrestricted model
  endpoint — is read from the code, so the document cannot go on
  asserting it after somebody changes it.
"""

from __future__ import annotations

import importlib.util
import pathlib
import re
import subprocess
import sys

import pytest

_ROOT = pathlib.Path(__file__).resolve().parent.parent
_GENERATOR = _ROOT / 'tools/generate_supplier_register.py'
_DOC = _ROOT / 'docs/SUPPLIERS.md'

_SPEC = importlib.util.spec_from_file_location('supplier_generator', _GENERATOR)
assert _SPEC and _SPEC.loader, f'cannot load {_GENERATOR}'
_GEN = importlib.util.module_from_spec(_SPEC)
sys.modules['supplier_generator'] = _GEN
_SPEC.loader.exec_module(_GEN)

SUPPLIERS = _GEN.SUPPLIERS
RECIPIENTS = _GEN.RECIPIENTS
PLACEHOLDER = _GEN.PLACEHOLDER
render = _GEN.render


class TestTheDocumentItself:
    def test_it_exists_and_says_it_is_generated(self):
        assert _DOC.exists(), _DOC
        text = _DOC.read_text()
        assert 'GENERATED by tools/generate_supplier_register.py' in text
        assert len(text.splitlines()) > 150

    def test_the_committed_file_matches_the_generator(self):
        assert (
            _DOC.read_text() == render()
        ), 'docs/SUPPLIERS.md and its generator disagree. Regenerate with `make docs`.'

    def test_the_generator_agrees_from_the_command_line(self):
        result = subprocess.run(  # noqa: S603
            [sys.executable, str(_GENERATOR), '--check'],
            capture_output=True,
            text=True,
            cwd=_ROOT,
        )
        assert result.returncode == 0, result.stderr or result.stdout

    def test_every_supplier_and_recipient_appears(self):
        text = _DOC.read_text()
        missing = [s.ref for s in SUPPLIERS if f'### `{s.ref}`' not in text]
        missing += [r.ref for r in RECIPIENTS if f'### {r.ref} —' not in text]
        assert not missing, missing


class TestTheSupplyChainIsDerived:
    def test_the_scan_found_images(self):
        """A comparison against an empty set would pass everything."""
        pinned = _GEN.pinned_images()
        assert len(pinned) >= 5, sorted(pinned)
        assert 'python:3.13-slim' in pinned, sorted(pinned)

    def test_every_pinned_image_is_in_the_register(self):
        """The completeness direction. A base image added to a Dockerfile
        without an entry here is how a supply chain drifts away from its
        description."""
        undeclared = _GEN.undeclared_images()
        assert not undeclared, f'these images are pinned in the build and missing from the register: {undeclared}'

    def test_no_register_entry_names_an_image_nothing_pins(self):
        """The other direction: a supplier that has been removed but is
        still declared makes the register look better maintained than it
        is."""
        stale = _GEN.stale_declarations()
        assert not stale, f'these are declared and pinned nowhere: {stale}'

    def test_the_sources_are_not_duplicated(self):
        """A multi-stage Dockerfile names its base twice and the prod
        compose file names Postgres once per service, which rendered as
        "Dockerfile, Dockerfile"."""
        for reference, sources in _GEN.pinned_images().items():
            assert len(sources) == len(set(sources)), f'{reference}: {sources}'

    def test_every_supplier_states_its_exposure(self):
        """A list of names is not an assessment. Each entry says what it
        would cost if that supplier shipped something malicious."""
        thin = sorted(s.ref for s in SUPPLIERS if len(s.exposure) < 80)
        assert not thin, f'these name a supplier without saying what it exposes: {thin}'

    def test_the_build_system_is_listed(self):
        """The supplier a customer can least verify. A register of base
        images that omitted the thing which builds them would be
        describing the part that is easy to check."""
        assert any('GitHub Actions' in s.ref for s in SUPPLIERS), [s.ref for s in SUPPLIERS]

    def test_the_registries_are_listed_as_well_as_the_images(self):
        """PyPI and npm are where most of the code comes from, and
        neither is an image."""
        refs = {s.ref for s in SUPPLIERS}
        assert 'PyPI' in refs and 'npm' in refs, sorted(refs)


class TestTheThreeCategoriesStaySeparate:
    def test_the_document_distinguishes_them_up_front(self):
        text = _DOC.read_text()
        assert '## The short answer, and why it needs three sections' in text
        prose = ' '.join(text.split())
        assert 'the vendor is not a processor' in prose

    def test_no_supplier_is_described_as_receiving_customer_data(self):
        """Treating a base image as a data processor is noise, and it is
        the mistake that makes a supplier register unreadable."""
        text = _DOC.read_text()
        section = text.split('## Suppliers — what the customer installs')[1].split('\n## ')[0]
        assert 'None of them sees customer data' in section

    def test_the_model_endpoint_is_a_recipient_and_is_flagged(self):
        """The only entry that changes a customer's obligations. A
        register that omitted it would have missed the point of C5."""
        recipient = next(r for r in RECIPIENTS if 'model endpoint' in r.name)
        assert 'source code' in recipient.reaches
        assert 'Article 28' in recipient.obligation

    def test_the_vendor_row_says_nothing_by_any_path(self):
        recipient = next(r for r in RECIPIENTS if r.name == 'The vendor')
        assert '**Nothing.**' in recipient.reaches
        assert 'no setting that would change it' in recipient.default

    def test_nothing_receives_anything_by_default(self):
        """ "We send telemetry unless you turn it off" is the claim this
        product exists not to make. Asserted per recipient rather than
        once in prose."""
        for recipient in RECIPIENTS:
            default = recipient.default.lower()
            assert (
                'nothing' in default or 'only once the customer' in default
            ), f'{recipient.ref} may receive data by default: {recipient.default}'


class TestTheFactIsReadFromTheCode:
    def test_the_model_endpoint_is_still_unrestricted(self):
        """The document tells a customer this value decides whether they
        have a processor to paper. If somebody restricts the URL to
        private ranges, that advice becomes wrong — so the generator
        refuses rather than letting it drift."""
        assert _GEN.model_endpoint_is_unrestricted()

    def test_the_document_says_a_test_keeps_that_claim_true(self):
        prose = ' '.join(_DOC.read_text().split())
        assert 'A test keeps this sentence true against the code' in prose


class TestWhatItRefusesToDo:
    @pytest.mark.parametrize(
        'field',
        [
            'Organisation maintaining this register',
            'Owner',
            'Review interval',
            'Approved by',
            'Date of approval',
        ],
    )
    def test_the_binding_fields_are_asked_for_and_left_blank(self, field):
        text = _DOC.read_text()
        row = next((line for line in text.splitlines() if line.startswith(f'| {field} |')), None)
        assert row, f'the register no longer asks for: {field}'
        assert PLACEHOLDER in row, f'{field} has been filled in by the generator: {row}'

    def test_it_does_not_assess_the_suppliers_for_the_customer(self):
        """Whether `python:3.13-slim` is acceptable is a judgement about a
        threat model this document does not know."""
        prose = ' '.join(_DOC.read_text().split())
        assert "Assess the suppliers on the customer's behalf" in prose

    def test_it_says_the_vendors_own_suppliers_are_elsewhere(self):
        """The company that builds this has an email provider and a cloud
        account. None of them touches a deployment, and they belong in
        the organisation's own register — which is OR-4 and stays
        `Process`."""
        prose = ' '.join(_DOC.read_text().split())
        assert "Cover the vendor's own suppliers" in prose
        assert '`OR-4`' in prose

    def test_it_does_not_claim_to_speak_for_the_sibling_repositories(self):
        """A customer installs three artefacts. This register describes
        one, and saying so is better than implying coverage."""
        prose = ' '.join(_DOC.read_text().split())
        assert 'ember-code' in prose and 'igni__code-index' in prose

    def test_it_declares_no_sub_processors_rather_than_inventing_any(self):
        prose = ' '.join(_DOC.read_text().split())
        assert 'no sub-processors' in prose
        assert 'there is no processing to contract for' in prose
        # And no table of them, which is what a boilerplate register has.
        assert not re.search(r'\|\s*Sub-?processor\s*\|', _DOC.read_text(), re.I)
