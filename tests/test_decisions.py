"""`docs/DECISIONS.md` must not go on asking a settled question.

B6. The roadmap said there were nine open decisions "listed at the end of"
the review log. There were five, in two notations, two of them
mid-document — and **one had already been answered**: DEC-10 asked for
real token revocation, B5 built it, and the document kept asking for a
pass.

That is F139 aimed at the one list whose whole purpose is to be read by
somebody deciding what to do next, and it is why this register is
generated. Each decision declares what would resolve it as a check
against the code, and the state is derived.

The rules:

* **every resolver must actually look at something.** A resolver that
  returns False because it cannot find a file leaves a decision
  permanently `open` for the wrong reason, which is worse than no state
  at all — the reader concludes nobody has decided when in fact nobody
  has checked;
* **DEC-10 must read `answered`.** It is the case that motivated the
  file, so it is the case pinned;
* **each decision offers at least two options and says what waiting
  costs.** One option is not a decision, and a cost nobody can state is
  a decision nobody prioritises;
* **origins resolve.** A decision citing a finding or section that does
  not exist reads as evidence and is not;
* **a decision a person has taken never reads `open`.** The two-state
  version of this file conflated "nobody has decided" with "decided, not
  yet built", and it is the first of those a reader acts on — by going
  and asking for a call that has already been made. That is F139 again,
  inside the file written to fix F139, which is why `decided` exists and
  why it outranks `unknown`.
"""

