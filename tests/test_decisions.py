class TestTheDocumentDoesNotDependOnASiblingCheckout:
    """The generated file must mean the same thing everywhere.

    Two resolvers read ``../ember-code``. When it is absent — which is
    always, in CI — they returned ``False``, which the state machine
    reads as "checked, and the code has not done it". So the committed
    document, generated on a machine where the sibling exists, never
    matched the one CI generated, and `test_the_committed_file_matches_the_generator`
    failed on every pull request regardless of its contents.

    Worse than the absence: when the sibling *is* present the answer
    depends on which branch it has checked out, so the document was a
    function of the reader's working tree.
    """

    def test_render_is_identical_without_the_sibling(self, monkeypatch):
        with_sibling = _GEN.render()
        monkeypatch.setattr(_GEN, '_EMBER_CODE', pathlib.Path('/nonexistent/ember-code'))
        without_sibling = _GEN.render()
        assert with_sibling == without_sibling

    def test_the_sibling_backed_decisions_say_where_the_evidence_is(self):
        backed = [d for d in _GEN.DECISIONS if d.evidence_in]
        assert backed, 'expected the cross-repo decisions to be marked'
        for decision in backed:
            assert decision.unverifiable, f'{decision.ref} must say why it cannot be checked here'

    def test_a_marked_decision_never_consults_its_resolver(self):
        """Even a resolver that would answer `True` must not move the
        state — otherwise the document drifts the moment somebody
        clones the sibling next door."""
        called = []

        def _would_say_yes() -> bool:
            called.append(True)
            return True

        decision = [d for d in _GEN.DECISIONS if d.evidence_in][0]
        original = _GEN.RESOLVERS[decision.resolver]
        _GEN.RESOLVERS[decision.resolver] = _would_say_yes
        try:
            assert _GEN.state_of(decision) == 'decided'
        finally:
            _GEN.RESOLVERS[decision.resolver] = original
        assert not called, 'a sibling-backed decision ran its resolver'
