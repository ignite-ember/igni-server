class TestADecisionAPersonTookNeverReadsOpen:
    """The rule that made `decided` exist.

    `open` is an instruction to a reader: go and get this decided. When
    the decision has already been taken and merely not built, that
    instruction wastes the one person who acted on the document — and it
    is indistinguishable from the register being out of date, which is
    the state this file was generated to make impossible.
    """

    def test_no_decision_with_a_recorded_answer_reads_open(self):
        offenders = [d.ref for d in DECISIONS if d.decided and state_of(d) == 'open']
        assert not offenders, offenders

    def test_decided_outranks_unknown(self):
        """A person choosing is a fact about the world, not about this
        repository. A resolver that cannot reach `ember-code` must not
        turn a taken decision back into an unanswered one."""

        def explode() -> bool:
            raise FileNotFoundError('no sibling checkout')

        RESOLVERS['exploding'] = explode
        try:
            cls = DECISIONS[0].__class__
            undecided = cls('DEC-x', 'q', ('F1',), 'c' * 80, (('a', 'b'), ('c', 'd')), 'r', 'exploding')
            assert state_of(undecided) == 'unknown'
            decided = cls(
                'DEC-y',
                'q',
                ('F1',),
                'c' * 80,
                (('a', 'b'), ('c', 'd')),
                'r',
                'exploding',
                decided='somebody chose',
            )
            assert state_of(decided) == 'decided', 'a check that could not look has overridden a decision somebody made'
        finally:
            del RESOLVERS['exploding']

    def test_answered_still_outranks_decided(self):
        """The other direction. Once the code shows it, the code is the
        better evidence — a `decided` state on built work would read as
        outstanding work."""
        cls = DECISIONS[0].__class__
        RESOLVERS['built'] = lambda: True
        try:
            decision = cls(
                'DEC-z',
                'q',
                ('F1',),
                'c' * 80,
                (('a', 'b'), ('c', 'd')),
                'r',
                'built',
                decided='somebody chose',
            )
            assert state_of(decision) == 'answered'
        finally:
            del RESOLVERS['built']

    def test_the_document_explains_the_state_rather_than_just_using_it(self):
        text = _DOC.read_text()
        assert '## The state `decided`, and why it had to be added' in text
        prose = ' '.join(text.split())
        assert 'answering one is not the same as building it' in prose
        assert 'outranks' in prose

    def test_every_decided_entry_says_what_was_chosen(self):
        """A state without the paragraph behind it is a claim the reader
        cannot check. `decided` with no text would be the register
        asserting somebody acted and declining to say what they did."""
        text = _DOC.read_text()
        for decision in DECISIONS:
            if state_of(decision) != 'decided':
                continue
            section = text.split(f'## {decision.ref} —')[1].split('\n## ')[0]
            assert '**Decided.**' in section, decision.ref

    def test_the_declined_recommendation_survives_the_decision(self):
        """DEC-13's recommendation declined to recommend, and the call
        went the other way from neither option being obvious. Rewriting
        it to agree with the outcome would make the register read as
        though engineering had always known — which is the kind of
        tidying that destroys the only useful thing a decision log has.
        """
        section = _DOC.read_text().split('## DEC-13 —')[1].split('\n## ')[0]
        assert 'No recommendation' in section
        assert '**Decided.** Remove the worker and Flower' in section

    def test_the_removal_decision_records_the_gap_it_leaves(self):
        """The worker promised recovery from missed webhooks and never
        delivered it. Deleting the code does not delete the need, and a
        removal that dropped the requirement along with the
        implementation would be the tidier, worse outcome."""
        section = _DOC.read_text().split('## DEC-13 —')[1].split('\n## ')[0]
        assert 'does not close the gap' in section.lower()
        assert 'missed webhooks is still a real need' in section


