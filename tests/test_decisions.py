class TestTheDocumentItself:
    def test_it_exists_and_says_it_is_generated(self):
        assert _DOC.exists(), _DOC
        text = _DOC.read_text()
        assert 'GENERATED by tools/generate_decisions.py' in text
        assert len(text.splitlines()) > 100

    def test_the_committed_file_matches_the_generator(self):
        assert (
            _DOC.read_text() == render()
        ), 'docs/DECISIONS.md and its generator disagree. Regenerate with `make docs`.'

    def test_the_generator_agrees_from_the_command_line(self):
        result = subprocess.run(  # noqa: S603
            [sys.executable, str(_GENERATOR), '--check'],
            capture_output=True,
            text=True,
            cwd=_ROOT,
        )
        assert result.returncode == 0, result.stderr or result.stdout

    def test_every_decision_appears(self):
        text = _DOC.read_text()
        missing = [d.ref for d in DECISIONS if f'## {d.ref} —' not in text]
        assert not missing, missing

    def test_the_numbering_has_no_gaps(self):
        refs = sorted(int(d.ref.removeprefix('DEC-')) for d in DECISIONS)
        assert refs == list(range(refs[0], refs[0] + len(refs))), refs


class TestEveryResolverLooksAtSomething:
    """The rule that matters most here.

    A resolver returning False because it cannot find a file leaves a
    decision permanently `open` for the wrong reason — and a reader
    concludes nobody has decided, when in fact nobody has checked.
    """

    def test_every_decision_names_a_resolver_that_exists(self):
        missing = sorted(d.ref for d in DECISIONS if d.resolver not in RESOLVERS)
        assert not missing, missing

    def test_the_revocation_resolver_reads_the_router_and_the_register(self):
        """It has to be both: either alone could be true while the other
        was not — a route with no verified control behind it, or a
        register row citing a route that had been renamed."""
        from app.main import app

        served = set(app.openapi()['paths'])
        assert '/v1/portal/me/revoke-sessions' in served
        assert _GEN.register_rows().get('AC-11') == 'Verified'
        assert _GEN.revocation_is_built() is True

    def test_the_landing_page_resolver_reads_a_file_that_exists(self):
        """The resolver must look at a real file. What it finds there is
        allowed to change — DEC-12 was decided and built, so this asserts
        the resolver has something to read rather than pinning an
        answer.

        The landing page itself, with the `/old` redirect DEC-12 chose,
        moved to the public site's own repository (igni-site) on
        2026-10-31, so the portal's routes no longer name any landing
        page. What the resolver can still establish here is that this
        repository does not route the retired one; the redirect is
        tested in igni-site."""
        routes = _ROOT / 'portal/src/App.tsx'
        assert routes.exists(), 'the resolver reads a file that is not there'
        assert 'Routes' in routes.read_text(), (
            'the resolver reads a file that is not the route table, so DEC-12 would '
            'read `answered` for the wrong reason'
        )
        assert _GEN.old_landing_route_is_gone() is True

    def test_the_celery_resolver_checks_both_resolutions(self):
        """Wiring a dispatcher and removing the worker are both answers.
        A resolver that only looked for one would call the other
        outcome `open` forever."""
        source = _GENERATOR.read_text()
        assert 'apply_async' in source and 'celery_worker:' in source

    def test_the_celery_resolver_reads_answered_by_removal(self):
        """The branch that had never been taken. Before DEC-13 only the
        dispatcher half of this resolver had ever returned True in
        anger — and a branch nothing has executed is R-8's shape."""
        assert _GEN.celery_question_is_settled() is True
        decision = next(d for d in DECISIONS if d.ref == 'DEC-13')
        assert state_of(decision) == 'answered'

    def test_the_cli_resolver_finds_the_sibling_setting(self):
        """`ember-code` is a separate checkout, so this is the one
        resolver that can legitimately not look — but when the checkout
        is present it must find the real default rather than silently
        answering False."""
        settings = _ROOT.parent / 'ember-code/src/ember_code/core/config/settings.py'
        if not settings.exists():
            pytest.skip('the ember-code checkout is not present — skipped, not passed')
        assert re.search(r'api_url[^=\n]*=\s*[\'"]', settings.read_text()), (
            'the resolver cannot find `api_url` in the sibling settings, so DEC-14 would read '
            '`open` whatever the default is'
        )
        # Not pinned either way: DEC-14 is decided and the change lands
        # in `ember-code`, so the value here is expected to flip. What is
        # pinned is that the resolver found the setting to read.
        assert isinstance(_GEN.cli_api_url_default_is_gone(), bool)

    def test_a_resolver_that_cannot_look_says_unknown_rather_than_open(self):
        """`state_of` catches an exception and reports `unknown`. Without
        that, a resolver reaching for an absent sibling repository would
        report `open` — a claim about a decision from a failure to
        look."""

        def explode() -> bool:
            raise FileNotFoundError('no sibling checkout')

        RESOLVERS['exploding'] = explode
        try:
            decision = DECISIONS[0].__class__(
                'DEC-x', 'q', ('F1',), 'c' * 80, (('a', 'b'), ('c', 'd')), 'r', 'exploding'
            )
            assert state_of(decision) == 'unknown'
        finally:
            del RESOLVERS['exploding']


