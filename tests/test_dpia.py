"""`docs/DPIA.md` must not pretend to be a DPIA.

C5, OR-6. Article 35 asks a **controller** to assess their own
processing. The vendor is neither controller nor processor — the software
runs in the customer's infrastructure and no data reaches the vendor
(DP-5) — so a vendor-written DPIA would be inventing a purpose and then
assessing its own invention.

What this document is: the half a controller cannot write without the
vendor. The rules:

* **the systematic description is derived**, from the same activity list
  as the Article 30 record, which is generated from the live schema. A
  migration that adds a personal-data table cannot leave this document
  describing the old one;
* **every measure is a `Verified` register row.** A safeguard offered to
  a controller under 35(7)(d) has to be one something asserts, or it is
  a promise dressed as a control;
* **every risk is a harm to a person**, not a system failure. That is
  what 35(7)(c) asks for and it is the question a security risk register
  does not answer — `RISK_ASSESSMENT.md` says what could break, this
  says what it would mean for somebody;
* **the data-flow claim tracks the code.** The document tells a
  controller they can point inference at a third party, because
  `InferenceBackend.base_url` accepts any absolute URL. If somebody
  restricts it, the document is wrong and the generator refuses;
* **eleven fields stay blank**, including the conclusion of the
  screening. The vendor's reading is offered as an input and labelled as
  one.
"""

from __future__ import annotations

import importlib.util
import pathlib
import re
import subprocess
import sys

import pytest

_ROOT = pathlib.Path(__file__).resolve().parent.parent
_GENERATOR = _ROOT / 'tools/generate_dpia.py'
_DPIA = _ROOT / 'docs/DPIA.md'

_SPEC = importlib.util.spec_from_file_location('dpia_generator', _GENERATOR)
assert _SPEC and _SPEC.loader, f'cannot load {_GENERATOR}'
_GEN = importlib.util.module_from_spec(_SPEC)
sys.modules['dpia_generator'] = _GEN
_SPEC.loader.exec_module(_GEN)

CRITERIA = _GEN.CRITERIA
SUBJECT_RISKS = _GEN.SUBJECT_RISKS
PLACEHOLDER = _GEN.PLACEHOLDER
render = _GEN.render
register_rows = _GEN.register_rows


class TestTheDocumentItself:
    def test_it_exists_and_says_it_is_generated(self):
        assert _DPIA.exists(), _DPIA
        text = _DPIA.read_text()
        assert 'GENERATED by tools/generate_dpia.py' in text
        assert len(text.splitlines()) > 200

    def test_the_committed_file_matches_the_generator(self):
        assert _DPIA.read_text() == render(), 'docs/DPIA.md and its generator disagree. Regenerate with `make docs`.'

    def test_the_generator_agrees_from_the_command_line(self):
        result = subprocess.run(  # noqa: S603
            [sys.executable, str(_GENERATOR), '--check'],
            capture_output=True,
            text=True,
            cwd=_ROOT,
        )
        assert result.returncode == 0, result.stderr or result.stdout

    def test_it_says_in_its_first_words_that_it_is_not_a_dpia(self):
        """The most important sentence in the file. A customer who
        mistakes this for their assessment has skipped the assessment."""
        text = _DPIA.read_text()
        assert '## This is not a DPIA' in text
        assert 'the customer is the controller' in text.lower()

    def test_it_does_not_claim_the_vendor_is_a_processor(self):
        """It is not one, and inventing that relationship would invent
        an Article 28 obligation and a reassurance at the same time —
        the same rule the Article 30 record carries."""
        prose = ' '.join(_DPIA.read_text().split()).lower()
        for phrase in ('as your processor', 'we process your data', 'data processing agreement with the vendor'):
            assert phrase not in prose, f'the DPIA implies a processor relationship: {phrase!r}'

    def test_it_does_not_claim_an_assessment_has_been_carried_out(self):
        prose = ' '.join(_DPIA.read_text().split()).lower()
        for phrase in ('we have carried out a dpia', 'this dpia concludes', 'the dpia has been completed'):
            assert phrase not in prose, phrase


class TestTheFourLimbsOfArticle357:
    @pytest.mark.parametrize(
        'limb',
        [
            'Article 35(7)(a) — systematic description of the processing',
            'Article 35(7)(b) — necessity and proportionality',
            'Article 35(7)(c) — risks to the rights and freedoms of data subjects',
            'Article 35(7)(d) — measures, safeguards and mechanisms',
        ],
    )
    def test_each_limb_has_its_own_section(self, limb):
        """35(7) has four requirements and a DPIA missing one is
        incomplete on its face."""
        assert f'## {limb}' in _DPIA.read_text(), limb

    def test_the_description_covers_every_processing_activity(self):
        """Derived from the Article 30 record's activity list, which is
        itself generated from the live schema — so this cannot describe
        a system the software no longer is."""
        rop = _GEN._rop()  # noqa: SLF001
        text = _DPIA.read_text()
        assert len(rop.ACTIVITIES) >= 6, len(rop.ACTIVITIES)
        missing = [a.name for a in rop.ACTIVITIES if f'| {a.name} |' not in text]
        assert not missing, f'these processing activities are missing from 35(7)(a): {missing}'

    def test_necessity_is_left_to_the_controller(self):
        text = _DPIA.read_text()
        section = text.split('## Article 35(7)(b)')[1].split('\n## ')[0]
        assert PLACEHOLDER in section, 'the necessity assessment has been filled in by the vendor'

    def test_the_measures_are_all_verified(self):
        offenders = _GEN.unverified_rows()
        assert not offenders, offenders

    def test_the_measures_section_names_rows_that_exist(self):
        """The 35(7)(d) table is prose rather than data, so its row ids
        are checked separately from the subject risks'."""
        text = _DPIA.read_text()
        section = text.split('## Article 35(7)(d)')[1].split('\n## ')[0]
        cited = set(re.findall(r'`([A-Z]{2}-\d+)`', section))
        assert len(cited) >= 15, sorted(cited)
        statuses = register_rows()
        unknown = sorted(row for row in cited if row not in statuses)
        assert not unknown, f'the measures table cites rows that do not exist: {unknown}'


class TestTheRisksAreAboutPeople:
    def test_every_risk_describes_a_harm_to_somebody(self):
        """35(7)(c) is about the rights and freedoms of natural persons.
        A row saying "the database could be read" has answered the
        security question instead."""
        offenders = _GEN.risks_without_a_harm()
        assert not offenders, offenders

    def test_every_cited_finding_exists(self):
        unknown = _GEN.unknown_findings()
        assert not unknown, unknown

    def test_every_cited_row_exists(self):
        unknown = _GEN.unknown_rows()
        assert not unknown, unknown

    def test_most_of_them_were_observed_here(self):
        """The unusual property of this assessment, and the one a
        controller should weigh: these are not hypotheses. A risk that
        has occurred once in a codebase is a different proposition from
        one nobody has seen."""
        observed = [r for r in SUBJECT_RISKS if r.findings]
        assert len(observed) >= 5, [r.ref for r in SUBJECT_RISKS]


class TestTheScreeningIsHonest:
    def test_it_screens_against_all_three_cases_of_article_35_3(self):
        refs = {c.ref for c in CRITERIA}
        for case in ('35(3)(a)', '35(3)(b)', '35(3)(c)'):
            assert case in refs, case

    def test_it_screens_against_the_nine_edpb_criteria(self):
        refs = {c.ref for c in CRITERIA}
        for index in range(1, 10):
            assert f'EDPB-{index}' in refs, f'EDPB-{index}'

    def test_every_verdict_is_from_the_vocabulary(self):
        wrong = sorted(f'{c.ref}={c.verdict}' for c in CRITERIA if c.verdict not in ('no', 'depends', 'yes'))
        assert not wrong, wrong

    def test_every_criterion_gives_a_reason(self):
        thin = sorted(c.ref for c in CRITERIA if len(c.finding) < 80)
        assert not thin, f'these screen a criterion without saying why: {thin}'

    def test_it_reaches_the_uncomfortable_conclusion(self):
        """The vendor's reading is that a DPIA is likely required, and
        the reason is that the audit trail this product is proud of is
        also a record of what employees did at work. A screening that
        concluded "no DPIA needed" would be the most convenient possible
        answer, and it would be wrong.
        """
        prose = ' '.join(_DPIA.read_text().split())
        assert 'a DPIA is likely to be required' in prose
        assert (
            'monitoring system' in prose
        ), 'the screening does not acknowledge that the audit trail is also a monitoring system'

    def test_the_determination_is_still_the_controllers(self):
        """Offered as an input. A vendor cannot determine whether
        somebody else's processing needs an assessment."""
        text = _DPIA.read_text()
        row = next(
            line for line in text.splitlines() if line.startswith('| Whether a DPIA is required for this deployment |')
        )
        assert PLACEHOLDER in row

    def test_the_free_text_caveat_is_stated(self):
        """The screening says no special-category data by design, and
        that claim is only true of the schema: a commit message is
        whatever somebody typed."""
        prose = ' '.join(_DPIA.read_text().split())
        assert 'The honest caveat is free text' in prose


class TestTheDataFlowClaimTracksTheCode:
    def test_base_url_still_accepts_any_host(self):
        """The document tells a controller they can point inference at a
        third party, and that a provider receiving their source code is a
        processor they must assess. If somebody restricts `base_url` to
        private ranges, that advice becomes wrong."""
        assert (
            _GEN.base_url_is_still_unrestricted()
        ), '`InferenceBackend.base_url` appears to be restricted now, so the data-flow section is out of date'

    def test_the_model_endpoint_is_named_as_the_one_that_matters(self):
        prose = ' '.join(_DPIA.read_text().split())
        assert 'The model endpoint is the one that matters' in prose
        assert 'becomes a processor they must assess' in prose

    def test_the_vendor_row_says_nothing_reaches_it(self):
        text = _DPIA.read_text()
        row = next(line for line in text.splitlines() if line.startswith('| The vendor |'))
        assert '**Nothing**' in row, row

    def test_it_lists_the_other_configured_destinations(self):
        """A DPIA that mentioned only the model endpoint would understate
        the flows. SMTP carries a commit message and an address;
        monitoring carries labels."""
        text = _DPIA.read_text()
        for destination in ('git provider', 'SMTP relay', 'Prometheus'):
            assert destination in text, destination


class TestWhatTheControllerMustStillDo:
    @pytest.mark.parametrize(
        'field',
        [
            'Controller',
            'Purposes of the processing (35(7)(a))',
            'Legal basis for each activity',
            'Necessity and proportionality assessment (35(7)(b))',
            'Whether a DPIA is required for this deployment',
            'Residual risk: acceptable or not (35(7)(d))',
            'Approved by',
            'Date of approval',
        ],
    )
    def test_the_judgement_fields_are_asked_for_and_left_blank(self, field):
        text = _DPIA.read_text()
        row = next((line for line in text.splitlines() if line.startswith(f'| {field} |')), None)
        assert row, f'the DPIA no longer asks for: {field}'
        assert PLACEHOLDER in row, f'{field} has been filled in by the generator: {row}'

    def test_it_ends_with_a_list_of_what_is_left(self):
        text = _DPIA.read_text()
        assert '## What a controller still has to do' in text
        section = text.split('## What a controller still has to do')[1]
        for expectation in ('retention windows', 'where inference runs', 'employee-monitoring'):
            assert expectation in section, expectation

    def test_it_names_the_gaps_a_controller_should_know_about(self):
        """DP-3, DP-4, DP-12 and LG-8. A measures section that listed
        only what works would be the same omission the risk assessment
        has a rule against."""
        text = _DPIA.read_text()
        for row in ('`DP-3`', '`DP-4`', '`DP-12`', '`LG-8`'):
            assert row in text, f'the DPIA does not disclose {row} as a gap'
