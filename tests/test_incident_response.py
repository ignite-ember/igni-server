"""`docs/INCIDENT_RESPONSE.md` must name things that exist.

C4, closing LG-8. This is the document with the shortest reading time
and the highest cost of being wrong: read once, under pressure, by
somebody who did not write it.

A generic plan costs time at the moment there is none. "Contain the
incident" is not an instruction. Worse, a plan naming a route that has
been renamed is actively harmful — somebody tries it, gets a 404, and
spends the worst ten minutes of the incident wondering what else in the
document is wrong.

So every step names a real thing and these rules check it:

* **`METHOD /path` against the live router.** The method is part of it
  deliberately, and it earned its place immediately: the plan said
  `GET /v1/portal/subject-access` and the route is a `POST`. Under
  pressure that is a 405 and a wasted minute;
* **alert names against the rules the chart ships**, so a renamed alert
  cannot leave phase 1 pointing at nothing;
* **files on disk**, and **register rows that must be `Verified`** — a
  containment lever resting on an unbuilt capability is a lever that
  will not move;
* **no technical step without something to use.** A step that is not
  marked as a decision must point at an endpoint, an alert or a file;
* **eleven fields stay blank.** Roles, contacts, severities, who may
  authorise deletion, who decides on notification. A plan naming a
  fictional on-call rota is worse than no plan, because somebody will
  follow it.
"""

from __future__ import annotations

import importlib.util
import pathlib
import re
import subprocess
import sys

import pytest

_ROOT = pathlib.Path(__file__).resolve().parent.parent
_GENERATOR = _ROOT / 'tools/generate_incident_response.py'
_PLAN = _ROOT / 'docs/INCIDENT_RESPONSE.md'

_SPEC = importlib.util.spec_from_file_location('ir_generator', _GENERATOR)
assert _SPEC and _SPEC.loader, f'cannot load {_GENERATOR}'
_GEN = importlib.util.module_from_spec(_SPEC)
sys.modules['ir_generator'] = _GEN
_SPEC.loader.exec_module(_GEN)

STEPS = _GEN.STEPS
PHASES = _GEN.PHASES
PLACEHOLDER = _GEN.PLACEHOLDER
render = _GEN.render
register_rows = _GEN.register_rows


class TestTheDocumentItself:
    def test_it_exists_and_says_it_is_generated(self):
        assert _PLAN.exists(), _PLAN
        text = _PLAN.read_text()
        assert 'GENERATED by tools/generate_incident_response.py' in text
        assert len(text.splitlines()) > 200

    def test_the_committed_file_matches_the_generator(self):
        assert _PLAN.read_text() == render(), (
            'docs/INCIDENT_RESPONSE.md and its generator disagree. Regenerate:\n'
            '    python tools/generate_incident_response.py'
        )

    def test_the_generator_agrees_from_the_command_line(self):
        result = subprocess.run(  # noqa: S603
            [sys.executable, str(_GENERATOR), '--check'],
            capture_output=True,
            text=True,
            cwd=_ROOT,
        )
        assert result.returncode == 0, result.stderr or result.stdout

    def test_every_phase_has_steps(self):
        """A phase heading with nothing under it is a plan with a gap
        where the hard part goes."""
        for number, name, _ in PHASES:
            count = sum(1 for s in STEPS if s.phase == number)
            assert count >= 3, f'phase {number} ({name}) has {count} step(s)'

    def test_every_step_appears_in_the_document(self):
        text = _PLAN.read_text()
        missing = [s.ref for s in STEPS if f'### {s.ref} —' not in text]
        assert not missing, missing

    def test_the_phases_are_in_the_order_they_happen(self):
        """Detect, triage, contain, investigate, notify, recover, learn.
        A plan that put containment before triage would be telling
        somebody to destroy evidence first."""
        text = _PLAN.read_text()
        positions = [text.index(f'## {number}. {name}') for number, name, _ in PHASES]
        assert positions == sorted(positions), 'the phases are out of order in the document'


class TestEveryStepNamesSomethingReal:
    def test_the_scans_found_their_sources(self):
        assert len(_GEN.served_operations()) > 50, len(_GEN.served_operations())
        assert len(_GEN.declared_alerts()) >= 8, sorted(_GEN.declared_alerts())
        assert len(register_rows()) > 40

    def test_every_endpoint_is_one_the_router_serves(self):
        """Method and path. `GET /v1/portal/subject-access` was in the
        first draft and the route is a POST — a 405 at the worst
        possible moment."""
        unknown = _GEN.unknown_endpoints()
        assert not unknown, (
            f'the plan names routes that do not exist: {unknown}. Somebody following this under '
            'pressure gets a 404 and stops trusting the document.'
        )

    def test_every_endpoint_carries_a_method(self):
        """A path with no verb leaves somebody guessing between PATCH
        and PUT."""
        bare = sorted(
            f'{s.ref}: {e}' for s in STEPS for e in s.endpoints if not re.match(r'^(GET|POST|PUT|PATCH|DELETE) /', e)
        )
        assert not bare, bare

    def test_every_alert_is_one_the_chart_ships(self):
        unknown = _GEN.unknown_alerts()
        assert not unknown, f'the plan names alerts that do not exist: {unknown}'

    def test_every_file_exists(self):
        missing = _GEN.missing_files()
        assert not missing, f'the plan names files that do not exist: {missing}'

    def test_every_cited_row_exists(self):
        unknown = _GEN.unknown_rows()
        assert not unknown, unknown

    def test_no_step_relies_on_an_unverified_capability(self):
        """A containment lever resting on a `Process` row is a lever that
        will not move when somebody pulls it."""
        offenders = _GEN.unverified_rows()
        assert not offenders, offenders

    def test_no_technical_step_is_an_empty_instruction(self):
        """ "Contain the incident" is not an instruction. A step that is
        not marked as a decision must point at something usable."""
        offenders = _GEN.steps_without_a_mechanism()
        assert not offenders, f'these say what to achieve and not what to use: {offenders}'

    def test_a_decision_step_claims_no_mechanism(self):
        """The other direction: a step marked as a person's decision must
        not also carry evidence, or the reader will think the software
        does it."""
        offenders = _GEN.organisational_steps_claiming_evidence()
        assert not offenders, offenders

    def test_the_document_marks_each_step_either_way(self):
        text = _PLAN.read_text()
        for step in STEPS:
            body = text.split(f'### {step.ref} —')[1].split('\n###')[0]
            if step.organisational:
                assert 'A decision, not a mechanism' in body, f'{step.ref} is not marked'
                assert PLACEHOLDER in body, f'{step.ref} carries no placeholder'
            else:
                assert '**Use:**' in body, f'{step.ref} names nothing to use'


class TestTheLeversAreTheOnesThatExist:
    """Phase 3 is the part somebody acts on. Each lever is checked
    against the test that proves it works, because a plan is only as
    good as the capability behind it."""

    def test_session_withdrawal_is_in_the_plan_and_proven(self):
        step = next(s for s in STEPS if s.ref == 'C1')
        assert any('revoke-sessions' in e for e in step.endpoints)
        assert 'AC-11' in step.rows
        assert (_ROOT / 'tests/test_withdrawn_sessions_are_refused.py').exists()

    def test_deactivation_is_separate_from_withdrawal(self):
        """They are different acts and both are usually right. A plan
        that conflated them would leave the responder thinking one had
        done the other's job — which is what the register itself claimed
        until B1 checked."""
        withdraw = next(s for s in STEPS if s.ref == 'C1')
        deactivate = next(s for s in STEPS if s.ref == 'C2')
        assert withdraw.endpoints != deactivate.endpoints
        assert (_ROOT / 'tests/test_what_deactivation_actually_revokes.py').exists()

    def test_only_the_last_containment_step_is_irreversible(self):
        """The most useful property on the page: you can act early
        without deciding anything permanent."""
        contain = [s for s in STEPS if s.phase == '3']
        assert contain[-1].ref == 'C6', [s.ref for s in contain]
        text = _PLAN.read_text()
        assert 'reversible except C6' in text
        body = text.split('### C6 —')[1].split('\n###')[0]
        assert 'irreversible' in body, 'C6 does not say that it cannot be undone'

    def test_recovery_points_at_the_drill_that_runs_in_ci(self):
        step = next(s for s in STEPS if s.ref == 'R1')
        assert 'tools/restore-drill.sh' in step.files
        assert 'DP-10' in step.rows


class TestWhatOnlyAnOrganisationCanSupply:
    @pytest.mark.parametrize(
        'field',
        [
            'Who declares an incident',
            'Incident lead (role, not a name)',
            'Out-of-hours contact',
            'Severity definitions and response times',
            'Who may authorise C6 (account deletion)',
            'Who decides on regulator notification',
            'Supervisory authority and its contact',
            'Approved by',
            'Date of approval',
        ],
    )
    def test_the_fields_are_asked_for_and_left_blank(self, field):
        text = _PLAN.read_text()
        row = next((line for line in text.splitlines() if line.startswith(f'| {field} |')), None)
        assert row, f'the plan no longer asks for: {field}'
        assert PLACEHOLDER in row, f'{field} has been filled in by the generator: {row}'

    def test_it_says_the_plan_is_not_usable_until_they_are_filled_in(self):
        """The honest state of LG-8: the levers are proven, the sequence
        is written, and the organisation around it does not exist."""
        prose = ' '.join(_PLAN.read_text().split())
        assert 'not usable until they are filled in' in prose

    def test_it_admits_it_has_never_been_rehearsed(self):
        """Every lever is individually tested; nobody has run them in
        sequence against a deployment. Saying so is the difference
        between a plan and a claim."""
        prose = ' '.join(_PLAN.read_text().split())
        assert 'never been rehearsed' in prose
        assert 'tabletop' in prose

    def test_it_warns_that_containment_destroys_evidence(self):
        """T1 before C1 is the opposite of the instinct, so the reason
        has to be on the page."""
        prose = ' '.join(_PLAN.read_text().split())
        assert 'Containment destroys evidence' in prose

    def test_it_states_that_no_vendor_is_watching(self):
        """For a self-hosted product this is the thing a responder most
        needs to know in the first minute: nobody else has noticed."""
        prose = ' '.join(_PLAN.read_text().split())
        assert 'Nothing here phones home' in prose

    def test_it_quotes_no_count_that_will_drift(self):
        """C3's lesson. The first draft said "Eleven rules ship with the
        chart", which is the same mistake the policies made with
        "ninety-five sections" and the SoA made by deriving one."""
        text = _PLAN.read_text()
        quoted = re.findall(
            r'\b(\d{2,}|ten|eleven|twelve|eight|nine)\b(?= (?:rules|alerts|steps|sections|metrics))',
            text,
            re.I,
        )
        assert not quoted, f'these counts will drift: {quoted}'


def test_one_command_regenerates_every_generated_document():
    """`make docs`, and `make check-docs` for CI.

    The five generated documents form a chain: the register's statuses
    feed the Statement of Applicability, its dispositions feed the risk
    assessment, and the risk assessment quotes each row's status back. So
    one register edit can make three documents stale at once — which
    happened the first time LG-8 moved from `Process` to `Partial`, and
    the suite failed on the risk assessment while I was looking at the
    incident plan.

    That is the chain working. It is also a good way to regenerate four
    of five and commit the fifth stale, so there is one target.
    """
    makefile = (_ROOT / 'Makefile').read_text()

    generators = sorted(p.name for p in (_ROOT / 'tools').glob('generate_*.py'))
    assert len(generators) >= 5, generators

    missing = [g for g in generators if g.removesuffix('.py') not in makefile]
    assert not missing, (
        f'these generators are not in `make docs`: {missing}. A generated document nothing '
        'regenerates is one somebody will commit stale.'
    )
    assert 'check-docs:' in makefile, 'there is no --check target for CI'
