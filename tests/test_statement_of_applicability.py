class TestTheDocumentItself:
    def test_it_exists_and_says_it_is_generated(self):
        assert _SOA.exists(), _SOA
        text = _SOA.read_text()
        assert 'GENERATED by tools/generate_statement_of_applicability.py' in text
        assert len(text.splitlines()) > 150, 'the SoA is suspiciously short'

    def test_the_committed_file_matches_the_generator(self):
        """Regenerate rather than edit."""
        assert _SOA.read_text() == render(), (
            'docs/STATEMENT_OF_APPLICABILITY.md and its generator disagree. Regenerate:\n'
            '    python tools/generate_statement_of_applicability.py'
        )

    def test_the_generator_agrees_from_the_command_line(self):
        """`--check` is what CI would call, so it has to reach the same
        verdict as importing the module."""
        result = subprocess.run(  # noqa: S603
            [sys.executable, str(_GENERATOR), '--check'],
            capture_output=True,
            text=True,
            cwd=_ROOT,
        )
        assert result.returncode == 0, result.stderr or result.stdout


class TestAllNinetyThreeControls:
    def test_the_count_is_ninety_three(self):
        assert len(ALL_CONTROLS) == 93, f'{len(ALL_CONTROLS)} controls, not 93'

    def test_each_theme_has_the_number_annex_a_gives_it(self):
        """37 / 8 / 14 / 34. A control dropped in an edit makes a tidier
        table, which is why the numbers are written down."""
        actual = {prefix: len(controls) for prefix, _, controls in THEMES}
        assert actual == EXPECTED_COUNTS, actual

    def test_no_control_appears_twice(self):
        refs = [c.ref for c in ALL_CONTROLS]
        duplicated = sorted({r for r in refs if refs.count(r) > 1})
        assert not duplicated, duplicated

    def test_every_reference_is_contiguous_within_its_theme(self):
        """5.1 to 5.37 with nothing missing, and so on. A gap is a
        control nobody decided about — which is the one thing an SoA
        cannot have."""
        for prefix, _, controls in THEMES:
            major = prefix.removeprefix('A.')
            minors = sorted(int(c.ref.split('.')[1]) for c in controls)
            assert all(c.ref.startswith(f'{major}.') for c in controls), prefix
            assert minors == list(range(1, len(controls) + 1)), f'{prefix} is not contiguous: {minors}'

    def test_every_control_has_a_title_and_a_justification(self):
        thin = sorted(c.ref for c in ALL_CONTROLS if len(c.title) < 5 or len(c.justification) < 20)
        assert not thin, f'these have no real title or no real justification: {thin}'

    def test_every_disposition_is_from_the_vocabulary(self):
        wrong = sorted(f'{c.ref}={c.disposition}' for c in ALL_CONTROLS if c.disposition not in DISPOSITIONS)
        assert not wrong, wrong

    def test_all_93_appear_in_the_rendered_document(self):
        """The tables, not the data structure. A render that dropped a
        theme would pass every check above."""
        text = _SOA.read_text()
        missing = [c.ref for c in ALL_CONTROLS if f'| {c.ref} | {c.title} |' not in text]
        assert not missing, f'these are in the generator and not in the document: {missing}'


class TestNoClaimWithoutEvidence:
    """The load-bearing rule, and the one that found four overclaims."""

    def test_the_register_was_read(self):
        """A comparison against an empty mapping passes everything."""
        rows = register_rows()
        assert len(rows) > 40, f'only parsed {len(rows)} register rows'
        assert rows.get('AC-11') == 'Verified', rows.get('AC-11')

    def test_every_cited_row_exists(self):
        unknown = unknown_citations()
        assert not unknown, (
            f'the SoA cites register rows that do not exist: {unknown}. A citation to nothing '
            'is worse than no citation, because it reads as evidence.'
        )

    def test_no_implementation_claim_rests_on_an_unverified_row(self):
        """`product` and `shared` say the software does something. The
        only evidence is a register row, and the register's statuses are
        asserted by `test_compliance_tracker_is_current.py` — so a claim
        resting on a `Process` or `Operator` row is unsupported.

        On the first run this failed four times: 5.14, 8.20, 8.21 and
        8.24 all cited DP-4 as evidence the software implements TLS.
        DP-4 is `Operator` — the product ships a terminator, but the DNS
        record and the certificate are the customer's. The prose says
        that now and the citation is gone.
        """
        unverified = unverified_citations()
        assert (
            not unverified
        ), 'these claim implementation on evidence the register has not verified:\n  ' + '\n  '.join(unverified)

    def test_product_and_shared_controls_cite_something(self):
        """A claim with no citation cannot be checked at all, which makes
        it the easiest kind to leave behind."""
        uncited = sorted(c.ref for c in ALL_CONTROLS if c.disposition in ('product', 'shared') and not c.rows)
        assert not uncited, f'these claim the software implements them and cite nothing: {uncited}'

    def test_organisation_and_operator_controls_claim_nothing(self):
        """The other direction. A control the organisation has to do must
        not carry evidence rows, or the table reads as though it were
        handled."""
        overreaching = sorted(
            f'{c.ref} ({c.disposition}) cites {list(c.rows)}'
            for c in ALL_CONTROLS
            if c.disposition in ('organisation', 'excluded') and c.rows
        )
        assert not overreaching, overreaching


class TestWhatOnlyAPersonCanSay:
    @pytest.mark.parametrize(
        'field',
        [
            'ISMS scope statement',
            'Legal entity',
            'Locations in scope',
            'Information systems in scope',
            'Exclusions from scope, with justification',
            'Approved by',
            'Date of approval',
        ],
    )
    def test_the_scope_fields_are_asked_for_and_left_blank(self, field):
        """A vendor-generated SoA that invented a scope statement would be
        describing an organisation it knows nothing about. Same refusal
        the Article 30 record makes about a legal basis."""
        text = _SOA.read_text()
        row = next((line for line in text.splitlines() if line.startswith(f'| {field} |')), None)
        assert row, f'the SoA no longer asks for: {field}'
        assert PLACEHOLDER in row, f'{field} has been filled in by the generator: {row}'

    def test_a_shared_control_shows_that_half_is_outstanding(self):
        """`shared` means the software does a defined part. The evidence
        cell carries both — the rows for our half and the placeholder for
        theirs — so a reader cannot mistake it for done.

        The generator's own docstring claimed this before the renderer
        did it, which is the shape of claim this review keeps finding.
        """
        text = _SOA.read_text()
        shared = [c for c in ALL_CONTROLS if c.disposition == 'shared']
        assert len(shared) > 10, f'only {len(shared)} shared controls; is the vocabulary still used?'

        for control in shared:
            row = next((line for line in text.splitlines() if line.startswith(f'| {control.ref} | ')), None)
            assert row, control.ref
            assert (
                PLACEHOLDER in row
            ), f'{control.ref} is `shared` and its row does not show the outstanding half: {row}'

    def test_it_does_not_claim_certification(self):
        """The register and the narrative are both held to this. An SoA is
        an input to certification, not evidence of it, and it is the
        document most likely to be mistaken for a certificate."""
        text = _SOA.read_text().lower()
        for phrase in ('we are iso 27001 certified', 'certified to iso', 'iso 27001 certified'):
            assert phrase not in text, f'the SoA implies certification: {phrase!r}'


class TestExclusionsAreArgued:
    def test_there_are_few_of_them(self):
        """An SoA that excludes half of Annex A is an SoA an auditor
        rejects. Two, and they are the two the software genuinely has no
        artefact for."""
        excluded = [c for c in ALL_CONTROLS if c.disposition == 'excluded']
        assert len(excluded) <= 5, f'{len(excluded)} exclusions is too many to defend: {[c.ref for c in excluded]}'

    def test_each_one_says_why_rather_than_not_yet(self):
        """`excluded` must never mean "not implemented". The words that
        would give that away are the ones checked for."""
        for control in ALL_CONTROLS:
            if control.disposition != 'excluded':
                continue
            reason = control.justification.lower()
            assert len(reason) > 60, f'{control.ref} is excluded without a real reason'
            for evasion in ('not yet', 'todo', 'planned', 'in progress', 'will be'):
                assert evasion not in reason, f'{control.ref} excludes a control by deferring it: {reason}'


