class TestTheTwoMappingsAgree:
    """The register cites Annex A controls in its Frameworks column. The
    SoA maps Annex A controls to register rows. Those are the same
    mapping written twice, and two copies of a mapping is F88's finding
    about the service contract — it described 60% of its own boundary.

    So: if a `Verified` row says it is evidence for `ISO A X.Y`, the
    SoA's X.Y has to cite that row. On the first run this found seven
    disagreements. Six were omissions here, added. The seventh was the
    register's: `CM-1` (changes are tested before release) cited
    `ISO A 8.31`, which is *separation of development, test and
    production environments* — that is `CM-6`. Change management is
    A 8.32 and security testing is A 8.29, and CM-1 now cites both.

    Rows that are not `Verified` are exempt in one direction: a `Process`
    row like `OR-2` legitimately cites A 5.1 while the SoA marks 5.1
    `organisation` and cites nothing, because citing an unverified row as
    evidence is the thing `TestNoClaimWithoutEvidence` forbids.
    """

    def _register_iso_claims(self) -> dict[str, tuple[str, list[str]]]:
        text = (_ROOT / 'docs/COMPLIANCE_TRACKER.md').read_text()
        claims: dict[str, tuple[str, list[str]]] = {}
        for match in re.finditer(r'^\|\s*([A-Z]{2}-\d+)\s*\|([^|]*)\|([^|]*)\|\s*`?([A-Za-z]+)`?\s*\|', text, re.M):
            claims[match.group(1)] = (match.group(4), re.findall(r'A (\d+\.\d+)', match.group(3)))
        return claims

    def test_the_scan_found_iso_citations(self):
        """A regex that matched nothing would make this class decorative."""
        claims = self._register_iso_claims()
        cited = {c for _, controls in claims.values() for c in controls}
        assert len(cited) >= 15, f'only found ISO citations for {sorted(cited)}'

    def test_every_verified_rows_iso_claim_is_reflected_in_the_soa(self):
        soa = {c.ref: c for c in ALL_CONTROLS}
        problems = []
        for row, (status, controls) in sorted(self._register_iso_claims().items()):
            if status != 'Verified':
                continue
            for ref in controls:
                control = soa.get(ref)
                if control is None:
                    problems.append(f'{row} cites A {ref}, which is not an Annex A control in the SoA')
                elif row not in control.rows:
                    problems.append(
                        f"{row} claims to be evidence for A {ref}, and the SoA's {ref} "
                        f'(`{control.disposition}`) cites {list(control.rows)}'
                    )
        assert not problems, 'the register and the SoA disagree about the mapping:\n  ' + '\n  '.join(problems)


def test_no_quoted_number_that_will_drift():
    """A generated document must not hardcode a count it does not derive.

    8.25 said "1920 server tests" while 1951 passed. That is the exact
    staleness this file exists to prevent, committed inside it — so the
    number is gone and the one that remains (the review-section count) is
    counted from `REVIEW_FINDINGS.md` at render time.
    """
    text = _SOA.read_text()

    quoted = re.findall(r'\b(\d{2,})\b(?= (?:server tests|tests|findings|review sections))', text)
    assert not quoted, (
        f'these counts are quoted: {quoted}. A count in a generated document is either stale or '
        'a coupling that makes the document stale — the review-section count was derived at '
        'first, which meant writing §96 made the committed file wrong. The claim worth making is '
        'that the record exists.'
    )
