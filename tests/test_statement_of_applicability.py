"""`docs/STATEMENT_OF_APPLICABILITY.md` must not overclaim, or go stale.

C1, OR-1. An SoA is 93 rows of "does this control apply, and what
implements it" — a list, citing evidence that lives somewhere else,
which makes it exactly the document F139 describes: `COMPLIANCE.md`
spent five passes telling customers that retention, subject access,
erasure, an SBOM and the air-gap test did not exist, all five of which
had been built.

So the SoA is generated, and these are the rules that make it worth
reading:

* **all 93 controls, once each**, in the four themes ISO/IEC 27001:2022
  gives them — 37, 8, 14, 34. A control quietly dropped in an edit is a
  smaller table, which looks like a tidier document;
* **the committed file is what the generator produces**, so a register
  row changing status shows up as a failing test rather than as a
  document nobody re-read;
* **no claim without verified evidence.** `product` and `shared` are
  assertions that something works, and the only evidence this document
  has is a register row. If that row is `Process`, `Operator` or
  missing, the generator refuses to render. This caught four overclaims
  on its first run: four controls cited DP-4 (TLS) as evidence the
  software implements something, and DP-4 is `Operator` because the DNS
  record and the certificate's trust chain are the customer's;
* **the scope is blank and stays blank.** Eight fields only the adopting
  organisation can state. A generated SoA that filled in a scope
  statement would be describing an organisation it knows nothing
  about — the same refusal the Article 30 record makes about a legal
  basis;
* **`excluded` is never used to mean "not done".** Two controls are
  declared not applicable, and an exclusion is the only kind of row an
  auditor argues with, so each one has to carry a reason.
"""

