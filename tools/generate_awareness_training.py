def modules() -> tuple[Module, ...]:
    return derived_modules() + WRITTEN_MODULES


def register_rows() -> dict[str, str]:
    import re

    rows: dict[str, str] = {}
    for match in re.finditer(
        r'^\|\s*([A-Z]{2}-\d+)\s*\|([^|]*)\|([^|]*)\|\s*`?([A-Za-z]+)`?\s*\|',
        _TRACKER.read_text(),
        re.M,
    ):
        rows[match.group(1)] = match.group(4)
    return rows


