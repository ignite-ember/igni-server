"""The keys igni signs its tokens with.

Generated by the server itself on first start (`SigningKeyDB.ensure`),
never supplied by an operator: nobody has to mint, paste or back up a
signing key, and nobody outside this database ever holds the private
half. Stored encrypted under `SECRET_ENCRYPTION_KEY`, so a database dump
alone does not let anybody sign.

A key is published from the moment it is written and signs from
`activates_at`. The gap is what makes a rotation safe across replicas
and across the services that cache igni's key set: everybody has the
new public key before the first token signed with it reaches them. A
superseded key stays published until every token it could have signed
has expired, then `SigningKeyDB.prune` removes it.
"""

from datetime import datetime, timezone

from sqlalchemy import Column, Index, Text, TIMESTAMP
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped

from app.db.sql.models import Base


class SigningKey(Base):
    __tablename__ = 'signing_keys'
    __table_args__ = (Index('idx_signing_keys_activates_at', 'activates_at'),)

    #: The RFC 7638 thumbprint of the public key; the JWT header's `kid`.
    kid: Mapped[str] = Column(Text, primary_key=True)
    algorithm: Mapped[str] = Column(Text, nullable=False, default='RS256')
    #: PKCS#8 PEM, Fernet-encrypted. See `app.services.secrets`. Marked so
    #: `tools/rotate_secret_key.py` is checked to cover it.
    encrypted_private_key: Mapped[str] = Column(Text, nullable=False, info={'encrypted': True})
    public_jwk: Mapped[dict[str, str]] = Column(JSONB, nullable=False)
    activates_at: Mapped[datetime] = Column(TIMESTAMP(timezone=True), nullable=False)
    created_at: Mapped[datetime] = Column(
        TIMESTAMP(timezone=True), nullable=False, default=lambda: datetime.now(timezone.utc)
    )
