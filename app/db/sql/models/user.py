"""User credentials — local auth store."""

from datetime import datetime, timezone
import uuid

from sqlalchemy import Boolean, Column, Index, Text, text, TIMESTAMP
from sqlalchemy.orm import Mapped

from app.db.sql.models import Base


class User(Base):
    __tablename__ = 'users'
    __table_args__ = (
        Index('idx_users_email', 'email', unique=True),
        # The access review orders by this and filters dormancy on it.
        # Declared here as well as in the migration because
        # `test_model_migration_parity.py` compares the two, and it caught
        # this being migration-only — the next autogenerated revision
        # would have dropped the index the report depends on.
        Index('idx_users_last_sign_in_at', 'last_sign_in_at'),
    )

    id: Mapped[str] = Column(Text, primary_key=True, default=lambda: str(uuid.uuid4()))
    user_id: Mapped[str] = Column(Text, nullable=False, unique=True)
    email: Mapped[str] = Column(Text, nullable=False, unique=True)
    hashed_password: Mapped[str] = Column(Text, nullable=False)
    full_name: Mapped[str | None] = Column(Text, nullable=True)
    auth_provider: Mapped[str] = Column(Text, nullable=False, server_default='email')  # 'email', 'google', 'oidc'
    created_at: Mapped[datetime] = Column(
        TIMESTAMP(timezone=True), nullable=False, default=lambda: datetime.now(timezone.utc)
    )
    updated_at: Mapped[datetime] = Column(
        TIMESTAMP(timezone=True), nullable=False, default=lambda: datetime.now(timezone.utc)
    )

    # AC-8 in the compliance tracker: dormancy is the strongest signal an
    # access review has, and nothing recorded it. Nullable with no
    # backfill — a deployment upgrading has no history to invent, and NULL
    # renders as *never* rather than as a date that would be a lie.
    last_sign_in_at: Mapped[datetime | None] = Column(TIMESTAMP(timezone=True), nullable=True)

    # DEC-10, built in B5. Revocation without a deny list: every token
    # carries `iat`, and a token issued before this instant is refused.
    # One column, one comparison against a row the request already
    # reads, and it withdraws *all* of a person's sessions at once —
    # which is the shape of the question an operator actually asks
    # ("assume everything they hold is compromised"), not "revoke this
    # one string".
    #
    # Nullable, and NULL means nothing has been revoked. A default of
    # `now()` would revoke every existing session on upgrade.
    tokens_valid_after: Mapped[datetime | None] = Column(TIMESTAMP(timezone=True), nullable=True)

    # When this person stopped working here. NULL means they have not.
    #
    # Deprovisioning, and it is a fact about the *account* rather than
    # about a membership. Deactivating somebody's membership in an
    # organisation was the only lever an administrator had, and it did
    # not deprovision them: every account is given a personal
    # organisation at sign-up, so a membership deactivated in the
    # company org left an active one beside it — and documents are
    # owned per user, not per organisation, so their work was never
    # the organisation's to withdraw in the first place.
    #
    # Checked where `tokens_valid_after` is checked, for the same
    # reason: it is one question about a person, asked once, at the
    # single point every authenticated request already passes.
    deactivated_at: Mapped[datetime | None] = Column(TIMESTAMP(timezone=True), nullable=True)

    #: May create organisations and make other super admins. The first
    #: account a deployment ever creates is one (`UserDB.create`), so a
    #: fresh install has somebody who can set it up; nobody else gets
    #: an organisation of their own. See the portal guide, ADMINISTERING_YOUR_ORGANISATION.md.
    is_super_admin: Mapped[bool] = Column(Boolean, nullable=False, server_default=text('false'))
